use lig_core::id::{ComponentId, ExprId, FragmentId, StrId};
use lig_ir::anchor::AnchorStep as IrStep;
use lig_ir::expr::Ty;
use lig_ir::fragment::{DynamicKind, FragmentIr, StateKind};
use lig_ir::module::{ReactionDecl, ReactionKind, ViewModule};
