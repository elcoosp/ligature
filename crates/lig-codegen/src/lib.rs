use quote::quote;
use std::collections::{HashMap, HashSet};

/// A codegen failure (fail-closed — BR-1 applies to emission too).
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum CodegenError {
    /// The IR contains a construct outside the M0 codegen subset.
    Unsupported(&'static str),
    /// The reactivity schedule is invalid (cycle/capacity).
    Schedule(ScheduleError),
    /// The readability budget is violated — a codegen bug, not a lint (§9.3).
    Readability(Vec<readability::Violation>),
}

impl core::fmt::Display for CodegenError {
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        match self {
            CodegenError::Unsupported(what) => write!(f, "outside the M0 codegen subset: {what}"),
            CodegenError::Schedule(e) => write!(f, "schedule error: {e:?}"),
            CodegenError::Readability(vs) => write!(f, "readability budget violated: {vs:?}"),
        }
    }
}

impl std::error::Error for CodegenError {}

/// The emitted artifact.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct GeneratedUnit {
    /// The generated Rust source text (prettyplease; byte-reproducible, D-8).
    pub text: String,
    /// The component that produced it.
    pub component: ComponentId,
    /// Stable name markers linking IR nodes to generated symbols (§9.4
    /// source maps consume these; no text scanning in consumers).
    pub links: GenLinks,
}

/// IR → generated-symbol links for one component.
#[derive(Debug, Clone, PartialEq, Eq, Default)]
pub struct GenLinks {
    /// The static-name prefix of this component (`Counter_`).
    pub prefix: String,
    /// `(reaction id, generated const name)` in reaction order.
    pub reactions: Vec<(u32, String)>,
    /// `(state field, generated setter fn name)`.
    pub setters: Vec<(String, String)>,
    /// `(template id, generated static name)`.
    pub templates: Vec<(u32, String)>,
}

/// One fragment's emission data.
struct FragInfo {
    id: FragmentId,
    template_id: usize,
    /// Anchor path per dynamic (dynamic index = hole index).
    hole_paths: Vec<Vec<IrStep>>,
    /// Anchor path per branch slot (If/For dynamics in order).
    branch_paths: Vec<Vec<IrStep>>,
}

/// Per-reaction emission data.
struct RxInfo<'m> {
    id: usize,
    decl: &'m ReactionDecl,
    const_name: String,
}

/// Generate the Rust source for one component (§9.2 shape).
///
/// # Errors
/// [`CodegenError`] for constructs outside the M0 subset, invalid schedules,
/// or readability-budget violations.
/// Generate the Rust source for one component (§9.2 shape) as a standalone
/// single-component file.
///
/// # Errors
/// [`CodegenError`] for constructs outside the M1 subset, invalid schedules,
/// or readability-budget violations.
// One arm per dynamic kind keeps the §9.2 emission auditable end-to-end.
pub fn generate_component(
    module: &ViewModule,
    component: ComponentId,
) -> Result<GeneratedUnit, CodegenError> {
    let (pieces, struct_name, digest, source_path, links) =
        generate_component_pieces(module, component)?;
    let source_path: &str = &source_path;
    let digest_lit = format!("{digest:#x}");
    let header = format!(
        "generated by ligature — do not edit\nsource: {source_path} (component digest {digest_lit})"
    );
    let doc = syn::LitStr::new(&header, Span::call_site());
    let all: proc_macro2::TokenStream = quote! {
        #[doc = #doc]
        pub mod generated {
            use ::lig_runtime::prelude::*;
            #(#pieces)*
        }
        pub use generated::#struct_name;
    };
    let file: syn::File = syn::parse2(all).expect("generated tokens must parse");
    let violations = readability::check(&file);
    if !violations.is_empty() {
        return Err(CodegenError::Readability(violations));
    }
    let text = prettyplease::unparse(&file);
    Ok(GeneratedUnit {
        text,
        component,
        links,
    })
}

/// Build the item tokens for one component (the shared core of
/// [`generate_component`] and [`generate_module`]). Returns the pieces, the
/// component struct ident, the surface digest, and the source path.
fn generate_component_pieces(
    module: &ViewModule,
    component: ComponentId,
) -> Result<
    (
        Vec<proc_macro2::TokenStream>,
        syn::Ident,
        u64,
        String,
        GenLinks,
    ),
    CodegenError,
> {
    let Some(decl) = module.components.get(component.get() as usize) else {
        return Err(CodegenError::Unsupported("missing component declaration"));
    };
    let Some(root) = module.component_root(component) else {
        return Err(CodegenError::Unsupported("missing component root"));
    };
    let schedule = build_schedule(module, root).map_err(CodegenError::Schedule)?;

    let struct_name = syn::Ident::new(&sanitize(module.strings.get(decl.name)), Span::call_site());
    let prefix = format!("{struct_name}_");

    // --- fragments -----------------------------------------------------------
    let frags = collect_frag_infos(module, root);
    let root_info = &frags[0];

    // --- templates (deduped by template id, BTree order = deterministic) ----
    let mut template_ids: Vec<usize> = frags.iter().map(|f| f.template_id).collect();
    template_ids.sort_unstable();
    template_ids.dedup();
    let template_statics: Vec<_> = template_ids
        .iter()
        .map(|&tid| template_gen::gen_template_static(module, tid, &prefix))
        .collect();

    // --- anchors per fragment ------------------------------------------------
    let anchor_statics: Vec<_> = frags
        .iter()
        .map(|f| {
            template_gen::gen_anchor_statics(
                f.id.get() as usize,
                &f.hole_paths,
                &f.branch_paths,
                &prefix,
            )
        })
        .collect();

    // --- reactions of this component (module order) ---------------------------
    let for_bodies: Vec<FragmentId> = module
        .fragments
        .iter()
        .flat_map(|f| f.dynamics.iter())
        .filter_map(|d| match &d.kind {
            DynamicKind::For(f) => Some(f.body),
            _ => None,
        })
        .collect();
    // M14: the fallback contents of For-body outlets run PER ITEM (the
    // per-item replay mounts them and applies their item-bound binds) —
    // their reactions get no general run arms (the item addressing does
    // not exist at flush scope; one reaction, N live items).
    let for_body_slot_fallbacks: Vec<FragmentId> = for_bodies
        .iter()
        .filter_map(|b| module.fragments.get(b.get() as usize))
        .flat_map(|body| body.dynamics.iter())
        .filter_map(|d| match &d.kind {
            DynamicKind::Slot {
                fallback: Some(fb), ..
            } => Some(*fb),
            _ => None,
        })
        .collect();
    let rxs: Vec<RxInfo<'_>> = module
        .reactions
        .iter()
        .enumerate()
        .filter(|(_, r)| {
            fragment_in_tree(&frags, r.owner)
                && !for_bodies.contains(&r.owner)
                && !for_body_slot_fallbacks.contains(&r.owner)
        })
        .map(|(id, r)| RxInfo {
            id,
            decl: r,
            const_name: reaction_const_name(module, r, id),
        })
        .collect();
    let n_reactions = rxs.len();
    let max_rx_id = rxs.iter().map(|r| r.id).max().map_or(0, |m| m + 1);
    let _ = max_rx_id;

    // --- SCHEDULE + WRITES -----------------------------------------------------
    let schedule_items = {
        let order: Vec<u8> = schedule.order.iter().map(|r| r.get() as u8).collect();
        let writes: Vec<u64> = (0..max_rx_id)
            .map(|i| schedule.reaction_writes.get(i).copied().unwrap_or(0))
            .collect();
        let writes_hi: Vec<u64> = (0..max_rx_id)
            .map(|i| schedule.reaction_writes_hi.get(i).copied().unwrap_or(0))
            .collect();
        let sched_name = syn::Ident::new(&format!("{prefix}SCHEDULE"), Span::call_site());
        quote! {
            static #sched_name: ::lig_runtime::Schedule = ::lig_runtime::Schedule {
                order: &[ #(#order),* ],
                writes: &[ #(#writes),* ],
                writes_hi: &[ #(#writes_hi),* ],
            };
        }
    };

    let sched_ident = syn::Ident::new(&format!("{prefix}SCHEDULE"), Span::call_site());

    // --- READS masks per state field -------------------------------------------
    let reads_consts: Vec<_> = {
        let mut out = Vec::new();
        let mut fields: Vec<StrPair> = schedule
            .field_readers
            .iter()
            .map(|(k, v)| (*k, *v))
            .collect();
        fields.sort_by_key(|(k, _)| k.get());
        for (field, mask) in fields {
            let base = sanitize(module.strings.get(field)).to_uppercase();
            let name = syn::Ident::new(&format!("{prefix}READS_{base}"), Span::call_site());
            out.push(quote! { const #name: u64 = #mask; });
            let hi = schedule.field_readers_hi.get(&field).copied().unwrap_or(0);
            if hi != 0 {
                // Spill-word readers (ids 64..128; bits are id − 64, M3).
                let name_hi =
                    syn::Ident::new(&format!("{prefix}READS_{base}_HI"), Span::call_site());
                out.push(quote! { const #name_hi: u64 = #hi; });
            }
        }
        out
    };

    // --- state struct fields + initializers --------------------------------------
    let mut struct_fields: Vec<proc_macro2::TokenStream> = Vec::new();
    let mut init_fields: Vec<proc_macro2::TokenStream> = Vec::new();
    for st in module.states.iter().filter(|s| s.owner == root) {
        let fname = syn::Ident::new(&sanitize(module.strings.get(st.name)), Span::call_site());
        let ty: syn::Type = syn::parse_str(&ty_name(&st.ty)).expect("valid type name");
        struct_fields.push(quote! { pub #fname: #ty });
        let init = match (st.kind, st.init) {
            (StateKind::Prop, _) => {
                // Props arrive through the `<Name>Props` argument (§7.6).
                quote! { props.#fname }
            }
            (StateKind::Signal | StateKind::Memo | StateKind::Cond | StateKind::Local, Some(e))
                if init_is_literal(module, e) =>
            {
                let v = gen_expr(module, e)?;
                if matches!(st.ty, Ty::Str) {
                    quote! { ::alloc::string::String::from(#v) }
                } else {
                    v
                }
            }
            (StateKind::Signal, Some(_)) => {
                return Err(CodegenError::Unsupported(
                    "non-literal signal initializers (M1 model codegen)",
                ));
            }
            _ => default_value(&st.ty),
        };
        init_fields.push(quote! { #fname: #init });
    }
    struct_fields.push(quote! { pub ev: ::lig_runtime::EvData });
    init_fields.push(quote! { ev: ::lig_runtime::EvData::new() });
    struct_fields.push(quote! { pub frag: ::lig_runtime::Fragment });

    // --- child component instances (fields + build) --------------------------------
    let mut component_uses = collect_component_uses(module, root);
    // Per-use child field names: a component used once keeps its base name;
    // further uses get a numbered suffix so every use site addresses its own
    // instance (§7.4 slot fills mount per use). The traversal is sorted, so
    // the numbering is deterministic (D-8).
    let mut seen_child_fields: std::collections::HashSet<String> = std::collections::HashSet::new();
    for use_site in &mut component_uses {
        let base = use_site.field.clone();
        if seen_child_fields.insert(base.clone()) {
            continue;
        }
        let mut n = 2usize;
        loop {
            let candidate = format!("{base}_{n}");
            if seen_child_fields.insert(candidate.clone()) {
                use_site.field = candidate;
                break;
            }
            n += 1;
        }
    }
    let component_field_map: HashMap<(u32, u32), String> = component_uses
        .iter()
        .map(|u| ((u.owner.get(), u.dyn_idx), u.field.clone()))
        .collect();
    // Slot-content addressing contexts (M7, two-sided walk in M9): fills of
    // every use site (matched against the child's root outlets, the child's
    // own fallback contents, and the use site's own fill contents) and this
    // component's own outlet fallbacks. Built after the per-use field
    // suffixing so the run arms address their own instance.
    let ctx_map: HashMap<u32, Ctx> = build_content_ctx(module, root, &component_uses)?;
    // Content-branch ref captures (M8): `ref={el}` on a branch hanging on
    // slot content captures per mount — inside the mounting If arm, keyed by
    // the branch fragment (the If's `then`). The build-body emission below
    // skips these (their fields still get declared + sentinel-initialized).
    let mut content_branch_refs: HashMap<u32, Vec<(usize, String)>> = HashMap::new();
    for f in &frags {
        let frag_ir = &module.fragments[f.id.get() as usize];
        for (di, d) in frag_ir.dynamics.iter().enumerate() {
            if !matches!(&d.kind, DynamicKind::Ref) {
                continue;
            }
            let ctx = ctx_of(module, &frags, &ctx_map, f.id);
            let Ctx::Branch { base, .. } = &ctx else {
                continue;
            };
            if !base.content_rooted() {
                continue;
            }
            let lig_ir::expr::Expr::Local(name) = module.exprs.get(d.expr) else {
                continue;
            };
            content_branch_refs
                .entry(f.id.get())
                .or_default()
                .push((di, sanitize(module.strings.get(*name))));
        }
    }
    for use_site in &component_uses {
        let (field, comp_idx) = (&use_site.field, use_site.comp_idx);
        let Some(decl) = module.components.get(comp_idx) else {
            return Err(CodegenError::Unsupported("missing component declaration"));
        };
        let child_name = sanitize(module.strings.get(decl.name));
        let fname = syn::Ident::new(field, Span::call_site());
        let child_ty = syn::Ident::new(&child_name, Span::call_site());
        let props_ty = syn::Ident::new(&format!("{child_name}Props"), Span::call_site());
        // M10 per-mount identity: a use on a BRANCH fragment (If/Show body —
        // any base, author or child side) rebuilds its instance per mount,
        // so the field is `Option<Child>` (built in the mounting arm,
        // disposed on unmount). Direct uses keep the eager M0 field.
        // M13 per-item instance identity: a use on a FOR-BODY fragment owns
        // a `Vec<Option<Child>>` — the generated reconcile mirrors the
        // keyed plan onto it (build + attach on insert, teardown on remove,
        // reposition on move), so every live item carries its own instance.
        // The store starts empty: items mount on the first reconcile. (The
        // list-body check comes FIRST: `ctx_of` classifies a For body as a
        // `Branch` ctx, but a direct item-body use is NOT a per-mount branch
        // use — the branch-in-item case is denied at the frontend.)
        if owner_is_list_body(module, &frags, use_site.owner) {
            struct_fields.push(quote! {
                pub #fname: ::alloc::vec::Vec<::core::option::Option<#child_ty>>
            });
            init_fields.push(quote! { #fname: ::alloc::vec::Vec::new() });
        } else if matches!(
            ctx_of(module, &frags, &ctx_map, use_site.owner),
            Ctx::Branch { .. }
        ) {
            struct_fields.push(quote! { pub #fname: Option<#child_ty> });
            init_fields.push(quote! { #fname: None });
        } else {
            struct_fields.push(quote! { pub #fname: #child_ty });
            init_fields.push(quote! {
                #fname: #child_ty::build(h, #props_ty::default())
            });
        }
    }

    // --- StyleProp prev slots (per-dynamic prev diff, §8.2/C5) ----------------------
    // Keyed per (fragment, dynamic) — two fragments in one tree may both
    // carry a StyleProp at dynamic index 0 (root + branch; root + two fills),
    // and one shared `p_0` field would collide (M7).
    let mut prev_fields: Vec<proc_macro2::TokenStream> = Vec::new();
    let mut prev_inits: Vec<proc_macro2::TokenStream> = Vec::new();
    for (frag_id, di) in collect_styleprop_dynamics(module, root) {
        let fname = syn::Ident::new(&format!("p_f{frag_id}_d{di}"), Span::call_site());
        prev_fields.push(quote! { #fname: ::alloc::string::String });
        prev_inits.push(quote! { #fname: ::alloc::string::String::new() });
    }
    struct_fields.extend(prev_fields);
    init_fields.extend(prev_inits);

    // --- branch leg trackers (M11): one u8 per If dynamic that carries an
    // else leg — the mounting arm records which leg is mounted (0 = none,
    // 1 = then, 2 = else) so the arm can swap legs; the then-only shape
    // stays tracker-free and byte-stable.
    for f in &frags {
        let frag_ir = &module.fragments[f.id.get() as usize];
        for (di, d) in frag_ir.dynamics.iter().enumerate() {
            let DynamicKind::If(i) = &d.kind else {
                continue;
            };
            if i.else_.is_none() {
                continue;
            }
            let fname = syn::Ident::new(&format!("leg_f{}_d{}", f.id.get(), di), Span::call_site());
            struct_fields.push(quote! { #fname: u8 });
            init_fields.push(quote! { #fname: 0u8 });
        }
    }

    // --- apply functions (grouped by (fragment, anchor) — C5) ---------------------
    let apply_fns = emit_apply_fns(module, &frags);
    let group_state_fields: Vec<proc_macro2::TokenStream> = Vec::new();

    // --- run arms -------------------------------------------------------------
    let mut run_arms: Vec<proc_macro2::TokenStream> = Vec::new();
    let mut list_methods: Vec<proc_macro2::TokenStream> = Vec::new();
    let mut item_methods: Vec<proc_macro2::TokenStream> = Vec::new();
    // M15: the per-item fire fns — `&mut self` methods, spliced into the
    // impl block (the per-item analogues of the event fns).
    let mut item_fire_fns: Vec<proc_macro2::TokenStream> = Vec::new();
    let mut key_methods: Vec<proc_macro2::TokenStream> = Vec::new();
    let mut ref_captures: Vec<(String, usize, Ctx, FragmentId)> = Vec::new();
    // M15: For-body fragments — their event effects dispatch through the
    // per-item fire fns, not the run dispatch (no item addressing in the
    // flush scope, the M13 replay discipline).
    let for_bodies: HashSet<u32> = module
        .fragments
        .iter()
        .flat_map(|f| f.dynamics.iter())
        .filter_map(|d| match &d.kind {
            DynamicKind::For(fo) => Some(fo.body.get()),
            _ => None,
        })
        .collect();
    for rx in &rxs {
        let cname = syn::Ident::new(&format!("{prefix}{}", rx.const_name), Span::call_site());
        match rx.decl.kind {
            ReactionKind::Memo { target } => {
                let tname =
                    syn::Ident::new(&sanitize(module.strings.get(target)), Span::call_site());
                let body = gen_expr(module, rx.decl.body)?;
                let reads_mask = field_mask(&schedule, target);
                let reads_mask_hi = schedule.field_readers_hi.get(&target).copied().unwrap_or(0);
                let spill_mark = if reads_mask_hi != 0 {
                    quote! { self.frag.dirty.mark_spill_word(0, #reads_mask_hi); }
                } else {
                    quote! {}
                };
                run_arms.push(quote! {
                    #cname => {
                        let next = #body;
                        if next != self.#tname {
                            self.#tname = next;
                            self.frag.mark_mask(#reads_mask);
                            #spill_mark
                        }
                    }
                });
            }
            ReactionKind::Effect { .. } => {
                // M15: a For-body event effect dispatches through the
                // per-item fire fn — the run dispatch has no item addressing
                // (the M13 replay discipline), so the arm is not emitted.
                if for_bodies.contains(&rx.decl.owner.get()) {
                    continue;
                }
                // event handler body: setter calls as statements
                let body = gen_expr(module, rx.decl.body)?;
                run_arms.push(quote! {
                    #cname => {
                        #body;
                    }
                });
            }
            ReactionKind::Bind { dynamic } => {
                let frag = module.fragments.get(rx.decl.owner.get() as usize);
                let Some(frag) = frag else { continue };
                let Some(d) = frag.dynamics.get(dynamic as usize) else {
                    continue;
                };
                let hole_idx = dynamic as usize;
                // One addressing discipline for every bind arm (M7): the
                // receiver comes from the owner fragment's context —
                // `self.frag`, a mounted branch, or mounted slot content.
                let ctx = ctx_of(module, &frags, &ctx_map, rx.decl.owner);
                let recv = ctx_recv(&ctx);
                match &d.kind {
                    DynamicKind::Text => {
                        let is_str =
                            value_kind(module, module.exprs.get(rx.decl.body)) == ValueKind::Str;
                        let body = gen_expr(module, rx.decl.body)?;
                        let inner = if is_str {
                            quote! { #recv.set_text(h, #hole_idx, &#body); }
                        } else {
                            quote! {
                                let mut buf = [0u8; 20];
                                #recv.set_text(h, #hole_idx, ::lig_runtime::format_i64(&mut buf, #body));
                            }
                        };
                        let scoped = ctx_scope(&ctx, inner);
                        run_arms.push(quote! { #cname => { #scoped } });
                    }
                    DynamicKind::Class => {
                        let body = gen_expr(module, rx.decl.body)?;
                        let inner = quote! { #recv.set_class(h, #hole_idx, Some(&(#body))); };
                        let scoped = ctx_scope(&ctx, inner);
                        run_arms.push(quote! { #cname => { #scoped } });
                    }
                    DynamicKind::Attr { key } => {
                        let key_lit = syn::LitStr::new(module.strings.get(*key), Span::call_site());
                        let body = gen_expr(module, rx.decl.body)?;
                        let is_str =
                            value_kind(module, module.exprs.get(rx.decl.body)) == ValueKind::Str;
                        let inner = if is_str {
                            quote! { #recv.set_attr(h, #hole_idx, #key_lit, Some(::lig_runtime::AttrVal::Str(&(#body)))); }
                        } else {
                            quote! { #recv.set_attr(h, #hole_idx, #key_lit, Some(::lig_runtime::AttrVal::Num((#body) as f64))); }
                        };
                        let scoped = ctx_scope(&ctx, inner);
                        run_arms.push(quote! { #cname => { #scoped } });
                    }
                    DynamicKind::If(if_ir) => {
                        let cond = gen_expr(module, if_ir.cond)?;
                        let slot = branch_slot_of_dynamic(frag, dynamic);
                        let Some(slot) = slot else { continue };
                        // M11 the else leg: both branch legs participate —
                        // then first, else second. The frontends lowered
                        // else since M2, but the mounting arm never mounted
                        // it (the emitted else template was dead and dynamic
                        // else content had no honest addressing).
                        let mut leg_ids: Vec<FragmentId> = vec![if_ir.then];
                        if let Some(el) = if_ir.else_ {
                            leg_ids.push(el);
                        }
                        let has_else = if_ir.else_.is_some();
                        let leg_field = has_else.then(|| {
                            syn::Ident::new(
                                &format!("leg_f{}_d{}", rx.decl.owner.get(), dynamic),
                                Span::call_site(),
                            )
                        });
                        let mut leg_statics: Vec<(syn::Ident, syn::Ident, syn::Ident)> =
                            Vec::with_capacity(leg_ids.len());
                        for &lid in &leg_ids {
                            let Some(info) = frags.iter().find(|f| f.id == lid) else {
                                return Err(CodegenError::Unsupported(
                                    "If branch fragment missing from the component tree",
                                ));
                            };
                            leg_statics.push((
                                tpl_ident(&prefix, info.template_id),
                                hole_ident(&prefix, info.id.get() as usize),
                                branch_ident(&prefix, info.id.get() as usize),
                            ));
                        }
                        // The mount rides the owner fragment's receiver: an If
                        // inside slot content mounts its branch on the
                        // content (M7), not on the parent's slab.
                        let content_rooted = ctx.content_rooted();
                        // M10/M11 branch-time assembly: any leg carrying
                        // component uses (per-mount identity — rebuild per
                        // mount, dispose per unmount) or slot outlets (their
                        // fills/fallbacks mount WITH the branch). An else leg
                        // always carries the marking story: its fresh binds
                        // initialize through the mount marking like a then
                        // branch's do.
                        let leg_frag_irs: Vec<Option<&FragmentIr>> = leg_ids
                            .iter()
                            .map(|lid| module.fragments.get(lid.get() as usize))
                            .collect();
                        let branch_has_components = leg_frag_irs.iter().any(|bf| {
                            bf.is_some_and(|f| {
                                f.dynamics
                                    .iter()
                                    .any(|d| matches!(d.kind, DynamicKind::Component(_)))
                            })
                        });
                        let branch_has_slots = leg_frag_irs.iter().any(|bf| {
                            bf.is_some_and(|f| {
                                f.dynamics
                                    .iter()
                                    .any(|d| matches!(d.kind, DynamicKind::Slot { .. }))
                            })
                        });
                        let needs_assembly =
                            content_rooted || branch_has_components || branch_has_slots || has_else;
                        // M17: a branch whose subtree carries a list remounts
                        // with a FRESH list table — the reconcile must re-run
                        // or the remounted list stays empty (the items are
                        // reconcile state, not template state). The mount
                        // mark (the M8 init discipline) re-runs the subtree's
                        // reactions on the next flush pass; scoped to
                        // list-carrying branches so every list-free unit's
                        // bytes stay pinned.
                        let branch_has_lists = subtree_has_for(module, if_ir.then);
                        let mount_flag = (!has_else && (needs_assembly || branch_has_lists))
                            .then(|| quote! { did_mount = true; });
                        // The mounted branch hangs on the fragment `ctx`
                        // addresses, at this dynamic's branch slot.
                        let branch_read = {
                            let base_read = ctx_frag_read(&ctx);
                            quote! { (#base_read).and_then(|f| f.branch(#slot)) }
                        };
                        // Per-mount instance rebuild (mount path) and dispose
                        // (unmount path) for each leg's component uses (M10
                        // per-mount identity, generalized to the else leg).
                        let mut leg_rebuilds: Vec<Vec<proc_macro2::TokenStream>> =
                            leg_frag_irs.iter().map(|_| Vec::new()).collect();
                        let mut leg_disposes: Vec<Vec<proc_macro2::TokenStream>> =
                            leg_frag_irs.iter().map(|_| Vec::new()).collect();
                        for (li, lid) in leg_ids.iter().enumerate() {
                            let Some(bf) = leg_frag_irs[li] else {
                                continue;
                            };
                            for (di, d) in bf.dynamics.iter().enumerate() {
                                let DynamicKind::Component(c) = &d.kind else {
                                    continue;
                                };
                                if owner_is_list_body(module, &frags, *lid) {
                                    return Err(CodegenError::Unsupported(
                                        "component uses inside list item bodies need per-item \
                                         instance identity (the keyed-component story)",
                                    ));
                                }
                                let field_name = component_field_map
                                    .get(&(lid.get(), di as u32))
                                    .cloned()
                                    .unwrap_or_else(|| field_name_for(module, c.component));
                                let field = syn::Ident::new(&field_name, Span::call_site());
                                let child_name = module
                                    .components
                                    .get(c.component.get() as usize)
                                    .map_or_else(
                                        || "Child".to_string(),
                                        |decl| sanitize(module.strings.get(decl.name)),
                                    );
                                let child_ty = syn::Ident::new(&child_name, Span::call_site());
                                let props_ty = syn::Ident::new(
                                    &format!("{child_name}Props"),
                                    Span::call_site(),
                                );
                                leg_rebuilds[li].push(quote! {
                                    self.#field =
                                        Some(#child_ty::build(h, #props_ty::default()));
                                });
                                leg_rebuilds[li].push(quote! {
                                    if let Some(n) = (#branch_read).map(|b| b.hole(#di)) {
                                        if let Some(inst) = self.#field.as_ref() {
                                            h.insert(n, inst.frag.roots()[0], 0);
                                        }
                                    }
                                });
                                leg_disposes[li].push(quote! {
                                    if let Some(inst) = self.#field.take() {
                                        inst.frag.teardown(h);
                                    }
                                });
                            }
                            // M13: the leg's subtree may own list bodies with
                            // per-item component stores — a branch unmount
                            // tears the items down with it, so the dispose
                            // list drains the stores (idempotent, like the
                            // Option takes: `drain` on an empty vec is a
                            // no-op).
                            for field in subtree_list_body_use_fields(
                                module,
                                &frags,
                                *lid,
                                &component_field_map,
                            ) {
                                let field = syn::Ident::new(&field, Span::call_site());
                                leg_disposes[li].push(quote! {
                                    for inst in self.#field.drain(..) {
                                        if let Some(c) = inst {
                                            c.frag.teardown(h);
                                        }
                                    }
                                });
                            }
                        }
                        // The branch-time slot assembly (M10/M11): outlets
                        // on either leg mount their use-site fill (author-side
                        // content) or their own fallback (any branch) at
                        // mount time, then the walk recurses into the freshly
                        // mounted content.
                        let mut leg_assembly: Vec<Vec<proc_macro2::TokenStream>> =
                            leg_frag_irs.iter().map(|_| Vec::new()).collect();
                        let mut leg_assembly_masks: Vec<u64> =
                            leg_frag_irs.iter().map(|_| 0u64).collect();
                        if branch_has_slots {
                            // The owning use site: author-side content
                            // names it through the ctx chain's innermost
                            // Fill field; child-side branches mount
                            // fallbacks only.
                            let use_site: Option<&ComponentUse> = ctx_content_field(&ctx)
                                .and_then(|field| component_uses.iter().find(|u| u.field == field));
                            for (li, bf) in leg_frag_irs.iter().enumerate() {
                                let Some(bf) = bf else {
                                    continue;
                                };
                                for (di, d) in bf.dynamics.iter().enumerate() {
                                    let DynamicKind::Slot {
                                        name: slot_name,
                                        fallback,
                                    } = &d.kind
                                    else {
                                        continue;
                                    };
                                    let mounted = use_site.and_then(|u| {
                                        u.ir.slots
                                            .iter()
                                            .find(|s| s.name == *slot_name)
                                            .and_then(|s| s.fallback)
                                            .map(|fb| (fb, false))
                                    });
                                    let (content_id, is_fallback) = match mounted {
                                        Some((fb, _)) => (fb, false),
                                        None => match fallback {
                                            Some(fb) => (*fb, true),
                                            None => continue,
                                        },
                                    };
                                    let origin = if is_fallback {
                                        quote!(::lig_runtime::SlotOrigin::Fallback)
                                    } else {
                                        quote!(::lig_runtime::SlotOrigin::Fill)
                                    };
                                    // Statics follow tree membership: author
                                    // content rides this component's prefix,
                                    // child content the child's.
                                    let content_in_parent =
                                        frags.iter().any(|f| f.id == content_id);
                                    let owner_prefix = if content_in_parent {
                                        prefix.clone()
                                    } else {
                                        let child_name = use_site
                                            .and_then(|u| module.components.get(u.comp_idx))
                                            .map_or_else(
                                                || "Child".to_string(),
                                                |decl| module.strings.get(decl.name).to_string(),
                                            );
                                        format!("{}_", sanitize(&child_name))
                                    };
                                    let content_frag = &module.fragments[content_id.get() as usize];
                                    let c_tpl = tpl_ident(
                                        &owner_prefix,
                                        content_frag.template.get() as usize,
                                    );
                                    let c_holes =
                                        hole_ident(&owner_prefix, content_id.get() as usize);
                                    let c_branches =
                                        branch_ident(&owner_prefix, content_id.get() as usize);
                                    // The mount lands on the BRANCH itself
                                    // (the outlet's owner fragment); the
                                    // content step addresses the freshly
                                    // mounted content for the recursion.
                                    let steps = vec![MutStep::Content {
                                        fill: !is_fallback,
                                        slot: di,
                                    }];
                                    // Recurse into the freshly mounted content
                                    // (nested outlets, grandchild holes,
                                    // events, refs) inside the same guards.
                                    let mut rec: Vec<proc_macro2::TokenStream> = Vec::new();
                                    walk_content_mounts(
                                        module,
                                        &frags,
                                        &prefix,
                                        &component_field_map,
                                        content_id,
                                        &quote!(b),
                                        &steps,
                                        use_site.map_or(&[], |u| &u.ir.slots),
                                        &owner_prefix,
                                        use_site.map_or("", |u| u.field.as_str()),
                                        false,
                                        0,
                                        &mut rec,
                                    )?;
                                    let body = quote! {
                                        b.mount_slot(h, #di, #origin, #c_tpl, #c_holes, #c_branches);
                                        #(#rec)*
                                    };
                                    leg_assembly[li].push(emit_assembly_walk(
                                        &ctx_frag_mut(&ctx),
                                        slot,
                                        &[],
                                        body,
                                    ));
                                    // Author-side fills are NOT under the
                                    // branch subtree: their reactions join the
                                    // mount mask so the fresh content's binds
                                    // initialize on the next flush pass.
                                    if !is_fallback {
                                        leg_assembly_masks[li] |=
                                            subtree_init_mask(module, content_id);
                                    }
                                }
                            }
                        }
                        let inner = if has_else {
                            // The tracked-leg shape (M11): a leg field makes
                            // the mounted leg explicit, so the arm can swap
                            // then ↔ else — `branch_is` alone cannot tell
                            // the two legs apart, and the else leg must mount
                            // when the condition is false (the fail-open this
                            // closes: the emitted else template was dead).
                            let leg = leg_field.as_ref().expect("else leg carries a tracker");
                            let (then_tpl, then_holes, then_branches) = &leg_statics[0];
                            let (else_tpl, else_holes, else_branches) = &leg_statics[1];
                            let mount_flag_then =
                                needs_assembly.then(|| quote! { mounted_leg = 1u8; });
                            let mount_flag_else =
                                needs_assembly.then(|| quote! { mounted_leg = 2u8; });
                            let rebuilds_then = &leg_rebuilds[0];
                            let rebuilds_else = &leg_rebuilds[1];
                            // The dispose lists of BOTH legs ride each
                            // transition: `Option::take` is idempotent, so
                            // running the off leg's list is a no-op.
                            let disposes = leg_disposes[0]
                                .iter()
                                .chain(leg_disposes[1].iter())
                                .collect::<Vec<_>>();
                            quote! {
                                let on = #cond;
                                if on {
                                    if !(#recv.branch_is(#slot) && self.#leg == 1u8) {
                                        #recv.unmount_branch(h, #slot);
                                        #(#disposes)*
                                        #recv.mount_branch(h, #slot, #then_tpl, #then_holes, #then_branches);
                                        self.#leg = 1u8;
                                        #mount_flag_then
                                        #(#rebuilds_then)*
                                    }
                                } else {
                                    if !(#recv.branch_is(#slot) && self.#leg == 2u8) {
                                        #recv.unmount_branch(h, #slot);
                                        #(#disposes)*
                                        #recv.mount_branch(h, #slot, #else_tpl, #else_holes, #else_branches);
                                        self.#leg = 2u8;
                                        #mount_flag_else
                                        #(#rebuilds_else)*
                                    }
                                }
                            }
                        } else {
                            let (then_tpl, then_holes, then_branches) = &leg_statics[0];
                            let rebuilds = &leg_rebuilds[0];
                            let disposes = &leg_disposes[0];
                            quote! {
                                let on = #cond;
                                if #recv.branch_is(#slot) != on {
                                    if on {
                                        #recv.mount_branch(h, #slot, #then_tpl, #then_holes, #then_branches);
                                        #mount_flag
                                        #(#rebuilds)*
                                    } else {
                                        #recv.unmount_branch(h, #slot);
                                        #(#disposes)*
                                    }
                                }
                            }
                        };
                        let scoped = ctx_scope(&ctx, inner);
                        if has_else && needs_assembly {
                            // The M11 mount marks, per leg: the leg field
                            // picks the freshly mounted leg, so the else
                            // leg's marking and assembly can never land on a
                            // mounted then branch (and vice versa). The mark,
                            // the assembly, and the captures sit OUTSIDE the
                            // unwrap so the fallback root (`self.frag`) stays
                            // borrowable (the M8 discipline).
                            let mut leg_blocks: Vec<proc_macro2::TokenStream> = Vec::new();
                            for (li, lid) in leg_ids.iter().enumerate() {
                                let mask = subtree_init_mask(module, *lid) | leg_assembly_masks[li];
                                let mask_lit =
                                    syn::LitInt::new(&format!("{mask:#x}"), Span::call_site());
                                let mut mount_attaches = Vec::new();
                                if let Some(bf) = leg_frag_irs[li] {
                                    for (edi, ed) in bf.dynamics.iter().enumerate() {
                                        let DynamicKind::Event { event, delegate } = &ed.kind
                                        else {
                                            continue;
                                        };
                                        let Some(rx_id) = ed.reaction else {
                                            continue;
                                        };
                                        let ev = syn::Ident::new(
                                            &format!("{event:?}"),
                                            Span::call_site(),
                                        );
                                        let hid = rx_id.get();
                                        mount_attaches.push(quote! {
                                            if let Some(n) = #branch_read.map(|b| b.hole(#edi)) {
                                                self.frag.attach_foreign(
                                                    n,
                                                    ::lig_runtime::EventKind::#ev,
                                                    ::lig_runtime::HandlerId(#hid),
                                                    #delegate,
                                                    h,
                                                );
                                            }
                                        });
                                    }
                                }
                                let mut mount_refs = Vec::new();
                                if let Some(caps) = content_branch_refs.get(&lid.get()) {
                                    for (hole, rname) in caps {
                                        let rfield = syn::Ident::new(
                                            &format!("ref_{rname}"),
                                            Span::call_site(),
                                        );
                                        mount_refs.push(quote! {
                                            if let Some(n) = #branch_read.map(|b| b.hole(#hole)) {
                                                self.#rfield = n;
                                            }
                                        });
                                    }
                                }
                                let assembly = &leg_assembly[li];
                                let leg_val = (li + 1) as u8;
                                leg_blocks.push(quote! {
                                    if mounted_leg == #leg_val {
                                        self.frag.mark_mask(#mask_lit);
                                        #(#assembly)*
                                        #(#mount_attaches)*
                                        #(#mount_refs)*
                                    }
                                });
                            }
                            run_arms.push(quote! {
                                #cname => {
                                    let mut mounted_leg: u8 = 0u8;
                                    #scoped
                                    #(#leg_blocks)*
                                }
                            });
                        } else if needs_assembly {
                            // The mount marks (M8, widened in M10): the fresh
                            // branch's own binds initialize on the NEXT flush
                            // pass (the loop re-enters through
                            // `produced.union(&rx.dirty().take())`); M10 adds
                            // the branch-mounted fills' reactions (per-mount
                            // identity: the prop-pass arms initialize the
                            // fresh instances) and the branch-time assembly's
                            // content. The mark, the assembly, and the
                            // captures sit OUTSIDE the unwrap so the fallback
                            // root (`self.frag`) stays borrowable.
                            let branch_mask =
                                subtree_init_mask(module, if_ir.then) | leg_assembly_masks[0];
                            let mask_lo_lit =
                                syn::LitInt::new(&format!("{branch_mask:#x}"), Span::call_site());
                            let mut mount_attaches = Vec::new();
                            if let Some(bf) = leg_frag_irs[0] {
                                for (edi, ed) in bf.dynamics.iter().enumerate() {
                                    let DynamicKind::Event { event, delegate } = &ed.kind else {
                                        continue;
                                    };
                                    let Some(rx_id) = ed.reaction else {
                                        continue;
                                    };
                                    let ev =
                                        syn::Ident::new(&format!("{event:?}"), Span::call_site());
                                    let hid = rx_id.get();
                                    mount_attaches.push(quote! {
                                        if let Some(n) = #branch_read.map(|b| b.hole(#edi)) {
                                            self.frag.attach_foreign(
                                                n,
                                                ::lig_runtime::EventKind::#ev,
                                                ::lig_runtime::HandlerId(#hid),
                                                #delegate,
                                                h,
                                            );
                                        }
                                    });
                                }
                            }
                            let mut mount_refs = Vec::new();
                            if let Some(caps) = content_branch_refs.get(&if_ir.then.get()) {
                                for (hole, rname) in caps {
                                    let rfield =
                                        syn::Ident::new(&format!("ref_{rname}"), Span::call_site());
                                    mount_refs.push(quote! {
                                        if let Some(n) = #branch_read.map(|b| b.hole(#hole)) {
                                            self.#rfield = n;
                                        }
                                    });
                                }
                            }
                            let assembly = &leg_assembly[0];
                            run_arms.push(quote! {
                                #cname => {
                                    let mut did_mount = false;
                                    #scoped
                                    if did_mount {
                                        self.frag.mark_mask(#mask_lo_lit);
                                        #(#assembly)*
                                        #(#mount_attaches)*
                                        #(#mount_refs)*
                                    }
                                }
                            });
                        } else if branch_has_lists {
                            // M17: the plain (no-assembly) arm for a
                            // list-carrying branch — the mount mark re-runs
                            // the subtree's reactions (the For's reconcile
                            // re-inserts into the fresh table, the binds
                            // re-apply) on the next flush pass. The mark sits
                            // OUTSIDE the unwrap so the fallback root
                            // (`self.frag`) stays borrowable (the M8
                            // discipline).
                            let branch_mask = subtree_init_mask(module, if_ir.then);
                            let mask_lo_lit =
                                syn::LitInt::new(&format!("{branch_mask:#x}"), Span::call_site());
                            run_arms.push(quote! {
                                #cname => {
                                    let mut did_mount = false;
                                    #scoped
                                    if did_mount {
                                        self.frag.mark_mask(#mask_lo_lit);
                                    }
                                }
                            });
                        } else {
                            run_arms.push(quote! { #cname => { #scoped } });
                        }
                    }
                    DynamicKind::For(for_ir) => {
                        // List reconcile (§7.5): keyed lists run the
                        // sequential keyed plan (`plan_keyed` — removes,
                        // moves, inserts as live-index steps, LIS-stable
                        // shape); unkeyed lists keep the Index diff.
                        // Emission goes through a per-For method plus the
                        // per-item replay (and a key fn when keyed).
                        let slot = branch_slot_of_dynamic(frag, dynamic);
                        let Some(slot) = slot else { continue };
                        let body_info = frags.iter().find(|f| f.id == for_ir.body);
                        let Some(body_info) = body_info else { continue };
                        let src_ty = codegen_ty_of(module, module.exprs.get(for_ir.source));
                        let lig_ir::expr::Ty::List(item_ty) = &src_ty else {
                            return Err(CodegenError::Unsupported(
                                "For source must lower to a list type",
                            ));
                        };
                        let item_ty = (**item_ty).clone();
                        let method = syn::Ident::new(
                            &format!("reconcile_f{}", for_ir.body.get()),
                            Span::call_site(),
                        );
                        if ctx == Ctx::Direct {
                            // Direct-rooted list (M0 shape, byte-stable): the
                            // reconcile is a `&mut self` method addressing
                            // `self.frag` — the list table hangs on the
                            // component's own fragment.
                            run_arms.push(quote! {
                                #cname => {
                                    self.#method(h, #slot);
                                }
                            });
                            let body_uses =
                                body_component_uses(module, for_ir, &component_field_map);
                            list_methods.extend(emit_list_method(
                                module, for_ir, &item_ty, body_info, &prefix, &body_uses,
                            )?);
                        } else {
                            // Composed list (M8 — branch-in-content and
                            // list-in-branch): the run arm pre-clones the
                            // source and the parent-state reads, unwraps the
                            // composed walk, and calls the associated
                            // reconcile with the receiver fragment. The
                            // associated fn takes no `self`, so the mutable
                            // walk borrow and the value reads never overlap.
                            let src = gen_expr(module, for_ir.source)?;
                            let src_ty_lit: syn::Type =
                                syn::parse_str(&ty_name(&item_ty)).expect("valid item type");
                            let reads = collect_body_reads(module, for_ir.body);
                            let read_declares: Vec<proc_macro2::TokenStream> = reads
                                .iter()
                                .map(|r| {
                                    let pname = syn::Ident::new(
                                        &format!("s_{}", sanitize(module.strings.get(*r))),
                                        Span::call_site(),
                                    );
                                    let fname = syn::Ident::new(
                                        &sanitize(module.strings.get(*r)),
                                        Span::call_site(),
                                    );
                                    quote! { let #pname = self.#fname.clone(); }
                                })
                                .collect();
                            let read_args: Vec<proc_macro2::TokenStream> = reads
                                .iter()
                                .map(|r| {
                                    let pname = syn::Ident::new(
                                        &format!("s_{}", sanitize(module.strings.get(*r))),
                                        Span::call_site(),
                                    );
                                    quote! { #pname.clone() }
                                })
                                .collect();
                            let recv = ctx_recv(&ctx);
                            // M13: the body's per-item instance stores ride
                            // the call as `&mut` params.
                            let body_uses =
                                body_component_uses(module, for_ir, &component_field_map);
                            let inst_args: Vec<proc_macro2::TokenStream> = body_uses
                                .iter()
                                .map(|u| {
                                    let field = syn::Ident::new(&u.field, Span::call_site());
                                    quote! { &mut self.#field }
                                })
                                .collect();
                            let call = quote! {
                                Self::#method(h, #recv, #slot, items, #(#read_args,)* #(#inst_args,)*);
                            };
                            let scoped = ctx_scope(&ctx, call);
                            run_arms.push(quote! {
                                #cname => {
                                    let items: ::alloc::vec::Vec<#src_ty_lit> =
                                        ::core::clone::Clone::clone(&(#src));
                                    #(#read_declares)*
                                    #scoped
                                }
                            });
                            list_methods.extend(emit_list_method_composed(
                                module, for_ir, &item_ty, body_info, &prefix, &body_uses,
                            )?);
                        }
                        if for_ir.key.is_some() {
                            key_methods.push(emit_key_method(module, for_ir, &item_ty)?);
                        }
                        let (apply_fn, fire_fns) =
                            emit_item_method(module, &frags, &prefix, for_ir, &item_ty)?;
                        item_methods.push(apply_fn);
                        item_fire_fns.extend(fire_fns);
                    }
                    DynamicKind::Component(c) => {
                        // Prop-pass (§7.6): direct writes on the child's
                        // state + a child flush; the child's own reactions
                        // run from its schedule. M10 per-mount identity: a
                        // use on a BRANCH fragment owns an Option field —
                        // the arm guards on the instance (a remounted branch
                        // rebuilt it; an unmounted one is `None`). Uses on
                        // For (list item) bodies stay fail-closed: per-item
                        // instance identity is the keyed-component story.
                        let per_mount = matches!(ctx, Ctx::Branch { .. });
                        if per_mount && owner_is_list_body(module, &frags, rx.decl.owner) {
                            return Err(CodegenError::Unsupported(
                                "component uses inside list item bodies need per-item instance \
                                 identity (the keyed-component story)",
                            ));
                        }
                        let field = syn::Ident::new(
                            &component_field_map
                                .get(&(rx.decl.owner.get(), dynamic))
                                .cloned()
                                .unwrap_or_else(|| field_name_for(module, c.component)),
                            Span::call_site(),
                        );
                        let mut sets = Vec::new();
                        for pb in &c.props {
                            let setter = syn::Ident::new(
                                &format!("set_{}", sanitize(module.strings.get(pb.prop))),
                                Span::call_site(),
                            );
                            let raw = gen_expr(module, pb.value)?;
                            // Setters take their value BY VALUE: a string
                            // literal interns into `String::from`, and every
                            // other expression clones — a state read would
                            // otherwise move out of `self` while the child
                            // field borrow is live (M9's slots-component
                            // fixture pins the state-read prop case).
                            let v = match module.exprs.get(pb.value) {
                                lig_ir::expr::Expr::Lit(lig_ir::expr::Lit::Str(_)) => {
                                    quote!(::alloc::string::String::from(#raw))
                                }
                                lig_ir::expr::Expr::Lit(
                                    lig_ir::expr::Lit::Int(_)
                                    | lig_ir::expr::Lit::Float(_)
                                    | lig_ir::expr::Lit::Bool(_)
                                    | lig_ir::expr::Lit::Null,
                                ) => raw,
                                _ => quote!((#raw).clone()),
                            };
                            let recv_expr = if per_mount {
                                quote!(c)
                            } else {
                                quote!(self.#field)
                            };
                            sets.push(quote! { #recv_expr.#setter(#v); });
                        }
                        if sets.is_empty() {
                            // No dynamic props: nothing to do per update.
                        } else if per_mount {
                            run_arms.push(quote! {
                                #cname => {
                                    if let Some(c) = self.#field.as_mut() {
                                        #(#sets)*
                                        ::lig_runtime::flush(c, h);
                                    }
                                }
                            });
                        } else {
                            run_arms.push(quote! {
                                #cname => {
                                    #(#sets)*
                                    ::lig_runtime::flush(&mut self.#field, h);
                                }
                            });
                        }
                    }
                    DynamicKind::StyleProp { prop } => {
                        let body = gen_expr(module, rx.decl.body)?;
                        let prop_id = prop.get();
                        let pname = syn::Ident::new(
                            &format!("p_f{}_d{dynamic}", rx.decl.owner.get()),
                            Span::call_site(),
                        );
                        let hole_idx = dynamic as usize;
                        let inner = quote! {
                            let v: ::alloc::string::String = ::core::clone::Clone::clone(&(#body));
                            if v != self.#pname {
                                self.#pname = v.clone();
                                #recv.set_style_dyn(
                                    h,
                                    #hole_idx,
                                    &[(#prop_id, ::lig_runtime::PropVal::Raw(&v))],
                                );
                            }
                        };
                        let scoped = ctx_scope(&ctx, inner);
                        run_arms.push(quote! { #cname => { #scoped } });
                    }
                    DynamicKind::Html => {
                        let body = gen_expr(module, rx.decl.body)?;
                        let hole_idx = dynamic as usize;
                        let inner = quote! { #recv.set_html(h, #hole_idx, &(#body)); };
                        let scoped = ctx_scope(&ctx, inner);
                        run_arms.push(quote! { #cname => { #scoped } });
                    }
                    DynamicKind::Ref => {
                        // Build-time: the ref local captures the hole NodeId.
                        if let lig_ir::expr::Expr::Local(name) = module.exprs.get(rx.decl.body) {
                            ref_captures.push((
                                sanitize(module.strings.get(*name)),
                                dynamic as usize,
                                ctx.clone(),
                                rx.decl.owner,
                            ));
                        } else {
                            return Err(CodegenError::Unsupported(
                                "ref must be a local binding in v1",
                            ));
                        }
                    }
                    DynamicKind::Event { event, delegate } => {
                        // attach-only metadata; the run arm is the Effect's
                        let _ = (event, delegate);
                    }
                    DynamicKind::Slot { .. } => {
                        // The parent mounts slot fills; the child reserves
                        // the hole (§7.4).
                    }
                    DynamicKind::Children | DynamicKind::PropPass { .. } | DynamicKind::Style => {
                        return Err(CodegenError::Unsupported(
                            "children/prop-pass/whole-style dynamics (M2)",
                        ));
                    }
                }
            }
        }
    }

    // --- attach list (event dynamics of ALL fragments in tree order) ----------
    // Direct-context events attach before the initial flush (§9.2 run-once
    // build shape, byte-stable since M0). Slot-content events attach at
    // mount time, inside the slot assembly above (the parent's build is the
    // only place both origins exist). Events inside mounted branches attach
    // after the flush, once the branch exists — the handler record lands on
    // the fragment whose reaction set owns the handler (M7).
    let mut attaches: Vec<proc_macro2::TokenStream> = Vec::new();
    let mut branch_attaches: Vec<proc_macro2::TokenStream> = Vec::new();
    let mut dispatch_lo: u64 = 0;
    let mut dispatch_hi: u64 = 0;
    for f in &frags {
        let frag = &module.fragments[f.id.get() as usize];
        for (di, d) in frag.dynamics.iter().enumerate() {
            if let DynamicKind::Event { event, delegate } = &d.kind {
                let Some(rx_id) = d.reaction else { continue };
                let id = rx_id.get();
                if id < 64 {
                    dispatch_lo |= 1u64 << id;
                } else {
                    dispatch_hi |= 1u64 << (id - 64);
                }
                // M15: per-item events attach at each item's insert (the
                // reconcile mirrors) and dispatch through the per-item fire
                // fns — no build-time attach record (the items do not exist
                // yet, and a branch-table lookup would be the wrong table).
                if for_bodies.contains(&f.id.get()) {
                    continue;
                }
                let ev = syn::Ident::new(&format!("{event:?}"), Span::call_site());
                let h = rx_id.get();
                let ctx = ctx_of(module, &frags, &ctx_map, f.id);
                match &ctx {
                    Ctx::Direct => {
                        attaches.push(quote! {
                            s.frag.attach(h, #di, ::lig_runtime::EventKind::#ev, ::lig_runtime::HandlerId(#h), #delegate);
                        });
                    }
                    Ctx::Branch { slot, base } if !base.content_rooted() => {
                        // Direct-rooted branch: attach after the flush, once
                        // the branch exists (M7 shape — flat walks stay
                        // byte-stable; nested walks read through the composed
                        // chain, M8). An else leg (M11) guards on the leg
                        // tracker — only the mounted leg's holes exist, and
                        // `hole()` falls back to the slab root out of bounds.
                        let slot = *slot;
                        let attach = if matches!(**base, Ctx::Direct) {
                            quote! {
                                if let Some(n) = s.frag.branch(#slot).map(|b| b.hole(#di)) {
                                    s.frag.attach_foreign(n, ::lig_runtime::EventKind::#ev, ::lig_runtime::HandlerId(#h), #delegate, h);
                                }
                            }
                        } else {
                            let read = ctx_frag_read(&ctx);
                            quote! {
                                if let Some(n) = #read.map(|b| b.hole(#di)) {
                                    s.frag.attach_foreign(n, ::lig_runtime::EventKind::#ev, ::lig_runtime::HandlerId(#h), #delegate, h);
                                }
                            }
                        };
                        match else_leg_of(module, &frags, f.id) {
                            Some((if_owner, dyn_idx, leg)) => {
                                let field = syn::Ident::new(
                                    &format!("leg_f{}_d{}", if_owner.get(), dyn_idx),
                                    Span::call_site(),
                                );
                                branch_attaches.push(quote! { if s.#field == #leg { #attach } });
                            }
                            None => branch_attaches.push(attach),
                        }
                    }
                    Ctx::Fill { .. } | Ctx::Fallback { .. } | Ctx::Branch { .. } => {
                        // Attached at mount time: content roots in the slot
                        // assembly (M7); content-rooted branches by the
                        // mounting If arm (M8 — per mount, since content
                        // branches mount and unmount with their content).
                    }
                }
            }
        }
    }

    // --- setters (signals + props; §7.6 props are plain fields with setters) ----
    let mut setters: Vec<proc_macro2::TokenStream> = Vec::new();
    for st in module
        .states
        .iter()
        .filter(|s| s.owner == root && (s.kind == StateKind::Signal || s.kind == StateKind::Prop))
    {
        let fname = syn::Ident::new(&sanitize(module.strings.get(st.name)), Span::call_site());
        let setter = syn::Ident::new(
            &format!("set_{}", sanitize(module.strings.get(st.name))),
            Span::call_site(),
        );
        let ty: syn::Type = syn::parse_str(&ty_name(&st.ty)).expect("valid type name");
        let mask = field_mask(&schedule, st.name);
        let mask_hi = schedule
            .field_readers_hi
            .get(&st.name)
            .copied()
            .unwrap_or(0);
        let spill_mark = if mask_hi != 0 {
            quote! { self.frag.dirty.mark_spill_word(0, #mask_hi); }
        } else {
            quote! {}
        };
        setters.push(quote! {
            /// Generated setter — the only write path for this signal (§9.2).
            pub fn #setter(&mut self, v: #ty) {
                self.#fname = v;
                self.frag.mark_mask(#mask);
                #spill_mark
            }
        });
    }

    // --- event glue fns ----------------------------------------------------------
    let mut event_fns: Vec<proc_macro2::TokenStream> = Vec::new();
    for rx in &rxs {
        if matches!(rx.decl.kind, ReactionKind::Effect { .. }) {
            let fname = syn::Ident::new(&format!("fire_{}", rx.id), Span::call_site());
            let rid = rx.id;
            event_fns.push(quote! {
                /// Dispatch glue: capture the event payload, mark the handler
                /// reaction, and flush (§10.1).
                pub fn #fname(&mut self, h: &mut dyn Host, ev: &::lig_runtime::EvData) {
                    self.ev = ev.clone();
                    self.frag.dirty.set(#rid as usize);
                    ::lig_runtime::flush(self, h);
                }
            });
        }
    }

    // --- build ----------------------------------------------------------------------
    // Exact per-bit init masks (M3 refinement, made exact per member in M7):
    // every reaction of THIS component runs once at build except the
    // event-driven handlers (their bits are exactly `dispatch_lo/hi`, the
    // event dynamics' reaction ids — script effects DO run at build, the
    // `effect_multi` demo pins it). The bit IS the reaction id (bits are
    // global reaction ids; a component that is not first in the module owns
    // ids past the low prefix, and the old `(1 << n) - 1` band marked the
    // wrong component's ids and missed its own late ones). The low word
    // carries ids 0..64 and the spill word ids 64..128 (bits are id − 64).
    if n_reactions > 128 {
        return Err(CodegenError::Unsupported(
            "more than 128 reactions in one component (spill-word dispatch cap)",
        ));
    }
    let mut init_mask: u64 = 0;
    let mut init_hi: u64 = 0;
    for rx in &rxs {
        let id = rx.id;
        if id < 64 {
            init_mask |= 1u64 << id;
        } else {
            init_hi |= 1u64 << (id - 64);
        }
    }
    init_mask &= !dispatch_lo;
    init_hi &= !dispatch_hi;
    let init_mask_lit = syn::LitInt::new(&format!("{init_mask:#x}"), Span::call_site());
    let init_spill = if init_hi != 0 {
        let init_hi_lit = syn::LitInt::new(&format!("{init_hi:#x}"), Span::call_site());
        quote! { s.frag.dirty.mark_spill_word(0, #init_hi_lit); }
    } else {
        quote! {}
    };
    let root_tpl = tpl_ident(&prefix, root_info.template_id);
    let root_holes = hole_ident(&prefix, root_info.id.get() as usize);
    let root_branches = branch_ident(&prefix, root_info.id.get() as usize);

    // Slot fills + outlet fallbacks (§7.4, M6; origins + the init-flush
    // story in M7): for every slot outlet in each used child, mount THIS use
    // site's fill by name (`SlotOrigin::Fill`); a use site that does not
    // fill the slot mounts the outlet's own fallback content
    // (`SlotOrigin::Fallback`). A fallback that carries dynamic binds is
    // initialized HERE: the child's build already flushed (its content was
    // not mounted yet), so the parent marks the child's fallback reactions
    // and flushes the child instance. Fill fragments live in the parent's
    // tree, fallback fragments in the child's — both sets of statics are
    // emitted into the same generated module scope.
    let mut slot_fills: Vec<proc_macro2::TokenStream> = Vec::new();
    // M10: the universal attach contract — every DIRECT component use's root
    // enters its owner's tree at the use hole before anything mounts into
    // it. Before M10 the child's DOM never attached (the M2-era silent drop:
    // Create commits existed, the positioning insert did not). Content uses
    // insert at content mount (M9's walk), branch uses per mount (M10).
    let mut child_attaches: Vec<proc_macro2::TokenStream> = Vec::new();
    for use_site in &component_uses {
        if !matches!(
            ctx_of(module, &frags, &ctx_map, use_site.owner),
            Ctx::Direct
        ) {
            continue;
        }
        let fname = syn::Ident::new(&use_site.field, Span::call_site());
        let di = use_site.dyn_idx as usize;
        child_attaches.push(quote! {
            h.insert(s.frag.hole(#di), s.#fname.frag.roots()[0], 0);
        });
    }
    for use_site in &component_uses {
        let Some(child_root) =
            module.component_root(lig_core::id::ComponentId::new(use_site.comp_idx as u32))
        else {
            continue;
        };
        let child_frag = &module.fragments[child_root.get() as usize];
        for (di, d) in child_frag.dynamics.iter().enumerate() {
            let DynamicKind::Slot {
                name: slot_name,
                fallback,
            } = &d.kind
            else {
                continue;
            };
            // This use's fill for the outlet's name, else the outlet fallback.
            let fill = use_site
                .ir
                .slots
                .iter()
                .find(|s| s.name == *slot_name)
                .and_then(|s| s.fallback);
            let (content_id, origin, is_fallback) = if let Some(fill_id) = fill {
                (fill_id, quote!(::lig_runtime::SlotOrigin::Fill), false)
            } else if let Some(fb) = *fallback {
                (fb, quote!(::lig_runtime::SlotOrigin::Fallback), true)
            } else {
                continue;
            };
            let content_frag = &module.fragments[content_id.get() as usize];
            // Fill fragments belong to the parent's tree (their statics ride
            // the parent prefix); fallback fragments belong to the child's.
            let owner_prefix = if frags.iter().any(|f| f.id == content_id) {
                prefix.clone()
            } else {
                let child_name = module.components.get(use_site.comp_idx).map_or_else(
                    || "Child".to_string(),
                    |decl| module.strings.get(decl.name).to_string(),
                );
                format!("{}_", sanitize(&child_name))
            };
            let tpl = tpl_ident(&owner_prefix, content_frag.template.get() as usize);
            let holes = hole_ident(&owner_prefix, content_id.get() as usize);
            let branches = branch_ident(&owner_prefix, content_id.get() as usize);
            let fname = syn::Ident::new(&use_site.field, Span::call_site());
            slot_fills.push(quote! {
                s.#fname.frag.mount_slot(h, #di, #origin, #tpl, #holes, #branches);
            });
            // Content event attaches (M7): the events of the mounted
            // content attach at mount time — the parent's build is the only
            // place both origins exist. The RECORD lands on the fragment
            // whose reaction set owns the handler: the parent's `s.frag`
            // for fills, the child instance's for fallbacks. `attach_foreign`
            // records across slabs; dispatch marks that fragment's dirty set.
            for (edi, ed) in content_frag.dynamics.iter().enumerate() {
                let DynamicKind::Event { event, delegate } = &ed.kind else {
                    continue;
                };
                let Some(rx_id) = ed.reaction else { continue };
                let ev = syn::Ident::new(&format!("{event:?}"), Span::call_site());
                let h = rx_id.get();
                if is_fallback {
                    slot_fills.push(quote! {
                        if let Some(n) = s.#fname.frag.slot_fallback(#di).map(|c| c.hole(#edi)) {
                            s.#fname.frag.attach_foreign(
                                n,
                                ::lig_runtime::EventKind::#ev,
                                ::lig_runtime::HandlerId(#h),
                                #delegate,
                                h,
                            );
                        }
                    });
                } else {
                    slot_fills.push(quote! {
                        if let Some(n) = s.#fname.frag.slot_fill(#di).map(|c| c.hole(#edi)) {
                            s.frag.attach_foreign(
                                n,
                                ::lig_runtime::EventKind::#ev,
                                ::lig_runtime::HandlerId(#h),
                                #delegate,
                                h,
                            );
                        }
                    });
                }
            }
            // Content refs of FALLBACK content (M7): the ref field is the
            // child's (the fallback fragment belongs to the child's tree) —
            // the parent writes it once the content is mounted. Fill refs
            // capture from the parent's own `ref_captures` (Ctx::Fill) below.
            if is_fallback {
                for (edi, ed) in content_frag.dynamics.iter().enumerate() {
                    if !matches!(&ed.kind, DynamicKind::Ref) {
                        continue;
                    }
                    let Some(lig_ir::expr::Expr::Local(name)) =
                        Some(module.exprs.get(ed.expr).clone())
                    else {
                        continue;
                    };
                    let rfield = syn::Ident::new(
                        &format!("ref_{}", sanitize(module.strings.get(name))),
                        Span::call_site(),
                    );
                    slot_fills.push(quote! {
                        if let Some(c) = s.#fname.frag.slot_fallback(#di) {
                            s.#fname.#rfield = c.hole(#edi);
                        }
                    });
                }
            }
            // The M9 recursive content walk: nested outlets mount their
            // fills/own fallbacks, grandchild roots insert, nested events
            // attach and nested refs capture — all at mount time, before
            // the fallback init-flush below (its binds address the freshly
            // mounted nested content).
            {
                let root_recv = quote! { s.#fname.frag };
                let steps: Vec<MutStep> = vec![MutStep::Content {
                    fill: !is_fallback,
                    slot: di,
                }];
                walk_content_mounts(
                    module,
                    &frags,
                    &prefix,
                    &component_field_map,
                    content_id,
                    &root_recv,
                    &steps,
                    &use_site.ir.slots,
                    &owner_prefix,
                    &use_site.field,
                    true,
                    0,
                    &mut slot_fills,
                )?;
            }
            if is_fallback {
                // The init-flush story (M7, subtree-wide in M8): mark the
                // child's fallback reactions and flush the child instance
                // with the content live — the child's build flushed before
                // the content was mounted, so its binds ran against an empty
                // outlet. With structural content the fallback's branch and
                // list fragments own reactions too (their binds, and the If
                // arms that mount the content's own branches) — the mask is
                // the exact per-reaction set of the whole fallback SUBTREE.
                // Event-driven handler reactions stay dispatch-driven (§9.2):
                // the subtree's event dynamics are excluded by id.
                let fb_subtree = subtree_ids(module, content_id);
                let mut fb_ev_lo: u64 = 0;
                let mut fb_ev_hi: u64 = 0;
                for &sid in &fb_subtree {
                    let Some(sf) = module.fragments.get(sid as usize) else {
                        continue;
                    };
                    for d in &sf.dynamics {
                        let DynamicKind::Event { .. } = &d.kind else {
                            continue;
                        };
                        let Some(rx_id) = d.reaction else {
                            continue;
                        };
                        let id = rx_id.get();
                        if id < 64 {
                            fb_ev_lo |= 1u64 << id;
                        } else {
                            fb_ev_hi |= 1u64 << (id - 64);
                        }
                    }
                }
                let mut fb_lo: u64 = 0;
                let mut fb_hi: u64 = 0;
                for (id, r) in module.reactions.iter().enumerate() {
                    if !fb_subtree.contains(&r.owner.get()) {
                        continue;
                    }
                    if id < 64 {
                        fb_lo |= 1u64 << id;
                    } else {
                        fb_hi |= 1u64 << (id - 64);
                    }
                }
                fb_lo &= !fb_ev_lo;
                fb_hi &= !fb_ev_hi;
                if fb_lo != 0 || fb_hi != 0 {
                    let fb_lo_lit = syn::LitInt::new(&format!("{fb_lo:#x}"), Span::call_site());
                    let fb_flush = if fb_hi != 0 {
                        let fb_hi_lit = syn::LitInt::new(&format!("{fb_hi:#x}"), Span::call_site());
                        quote! {
                            s.#fname.frag.dirty.mark_spill_word(0, #fb_hi_lit);
                            ::lig_runtime::flush(&mut s.#fname, h);
                        }
                    } else {
                        quote! { ::lig_runtime::flush(&mut s.#fname, h); }
                    };
                    slot_fills.push(quote! {
                        s.#fname.frag.mark_mask(#fb_lo_lit);
                        #fb_flush
                    });
                }
            }
        }
    }

    // Ref captures (M7 split): `ref={el}` stores the hole NodeId on the
    // named field — the hole of the fragment the ref lives on. Direct refs
    // capture from `self.frag` in the build body; slot-content refs capture
    // once the parent mounts the content (fills write the parent's field;
    // fallback refs are the CHILD's field — the fallback fragment belongs to
    // the child's tree — and the parent writes it post-mount); branch refs
    // capture after the initial flush mounts the branch. Every ref field
    // starts as the absent sentinel `NodeId(u32::MAX)`.
    let mut ref_inits: Vec<proc_macro2::TokenStream> = Vec::new();
    let mut content_ref_inits: Vec<proc_macro2::TokenStream> = Vec::new();
    let mut branch_ref_inits: Vec<proc_macro2::TokenStream> = Vec::new();
    for (name, hole, ctx, ref_owner) in &ref_captures {
        let fname = syn::Ident::new(&format!("ref_{name}"), Span::call_site());
        match ctx {
            Ctx::Direct => {
                ref_inits.push(quote! { s.#fname = s.frag.hole(#hole); });
            }
            Ctx::Branch { slot, base } if !base.content_rooted() => {
                let slot = *slot;
                let capture = if matches!(**base, Ctx::Direct) {
                    quote! {
                        if let Some(b) = s.frag.branch(#slot) {
                            s.#fname = b.hole(#hole);
                        }
                    }
                } else {
                    // Nested Direct-rooted branch: read through the composed
                    // chain (M8).
                    let read = ctx_frag_read(ctx);
                    quote! {
                        if let Some(n) = #read.map(|b| b.hole(#hole)) {
                            s.#fname = n;
                        }
                    }
                };
                // An else leg (M11) guards on the leg tracker: only the
                // mounted leg's holes exist.
                match else_leg_of(module, &frags, *ref_owner) {
                    Some((if_owner, dyn_idx, leg)) => {
                        let field = syn::Ident::new(
                            &format!("leg_f{}_d{}", if_owner.get(), dyn_idx),
                            Span::call_site(),
                        );
                        branch_ref_inits.push(quote! { if s.#field == #leg { #capture } });
                    }
                    None => branch_ref_inits.push(capture),
                }
            }
            Ctx::Fill { field, slot, .. } => {
                let field = syn::Ident::new(field, Span::call_site());
                content_ref_inits.push(quote! {
                    if let Some(c) = s.#field.frag.slot_fill(#slot) {
                        s.#fname = c.hole(#hole);
                    }
                });
            }
            Ctx::Branch { .. } | Ctx::Fallback { .. } => {
                // Content-rooted branches: captured at mount time by the
                // mounting If arm (M8). Fallbacks: captured by the PARENT at
                // mount time (the content does not exist in this build yet).
                // Either way the field is declared + sentinel-initialized
                // below so the mount-time write has a target.
            }
        }
    }
    for (name, _hole, _ctx, _owner) in &ref_captures {
        let fname = syn::Ident::new(&format!("ref_{name}"), Span::call_site());
        struct_fields.push(quote! { pub #fname: ::lig_runtime::NodeId });
        init_fields.push(quote! { #fname: ::lig_runtime::NodeId(u32::MAX) });
    }

    // Props struct: fields mirror the component's Prop declarations (§7.6).
    let decl = module.components.get(component.get() as usize);
    let props_fields: Vec<proc_macro2::TokenStream> = decl
        .map(|d| {
            d.props
                .iter()
                .map(|p| {
                    let f =
                        syn::Ident::new(&sanitize(module.strings.get(p.name)), Span::call_site());
                    let ty: syn::Type = syn::parse_str(&ty_name(&p.ty)).expect("valid type name");
                    quote! { pub #f: #ty }
                })
                .collect()
        })
        .unwrap_or_default();
    let props_ty = syn::Ident::new(&format!("{struct_name}Props"), Span::call_site());

    let digest = module.fingerprint_fragment(root);
    let source_path = module
        .source_files
        .first()
        .map_or("unknown", |f| f.path.as_str());

    // --- assemble ------------------------------------------------------------
    let group_inits: Vec<proc_macro2::TokenStream> = Vec::new();
    let mut pieces: Vec<proc_macro2::TokenStream> = Vec::new();

    let n_rx = syn::Ident::new(&format!("{prefix}N_REACTIONS"), Span::call_site());
    pieces.push(quote! {
        pub struct #struct_name {
            #(#struct_fields,)*
            #(#group_state_fields,)*
        }
        #[derive(Default)]
        pub struct #props_ty {
            #(#props_fields,)*
        }
        const #n_rx: usize = #n_reactions;
    });
    pieces.extend(template_statics);
    pieces.extend(anchor_statics);
    pieces.push(schedule_items);
    for c in reads_consts {
        pieces.push(quote! { #c });
    }
    for rx in &rxs {
        let cname = syn::Ident::new(&format!("{prefix}{}", rx.const_name), Span::call_site());
        let rid = rx.id as u8;
        pieces.push(quote! { const #cname: u8 = #rid; });
    }
    pieces.push(quote! {
        impl #struct_name {
            #(#setters)*

            #(#event_fns)*

            #(#list_methods)*

            #(#item_fire_fns)*

            /// Run-once build (C4): executes top-to-bottom; reactivity lives
            /// exclusively in reactions. M7 phases: child attach (M10 — each
            /// direct use's root enters the owner tree at its use hole) →
            /// slot assembly (mounts, content attaches, fallback init-flush)
            /// → direct ref captures → direct attaches → the initial flush
            /// (memos + binds) → branch attaches + branch ref captures
            /// (branch content exists only after the flush).
            pub fn build(h: &mut dyn Host, props: #props_ty) -> Self {
                let mut s = Self {
                    #(#init_fields,)*
                    #(#group_inits,)*
                    frag: ::lig_runtime::Fragment::new(h, #root_tpl, #root_holes, #root_branches),
                };
                #(#child_attaches)*
                #(#slot_fills)*
                #(#ref_inits)*
                #(#content_ref_inits)*
                #(#attaches)*
                // Initial pass: memos + binds only — dispatch-driven handler
                // reactions run on events, never at build (§9.2 run-once).
                s.frag.mark_mask(#init_mask_lit);
                #init_spill
                ::lig_runtime::flush(&mut s, h);
                #(#branch_attaches)*
                #(#branch_ref_inits)*
                s
            }
        }
    });
    pieces.push(quote! {
        impl ::lig_runtime::Reactions for #struct_name {
            fn schedule(&self) -> &'static ::lig_runtime::Schedule {
                &#sched_ident
            }

            fn dirty(&mut self) -> &mut ::lig_runtime::DirtySet {
                &mut self.frag.dirty
            }

            fn run(&mut self, h: &mut dyn Host, r: u8) {
                match r {
                    #(#run_arms)*
                    _ => {}
                }
            }
        }
    });
    pieces.extend(apply_fns);
    pieces.extend(item_methods);
    pieces.extend(key_methods);
    pieces.push(template_gen::gen_style_table(module, &prefix));

    // IR → generated-symbol links (source maps, §9.4).
    let links = GenLinks {
        prefix: prefix.clone(),
        reactions: rxs
            .iter()
            .map(|rx| (rx.id as u32, format!("{prefix}{}", rx.const_name)))
            .collect(),
        setters: module
            .states
            .iter()
            .filter(|st| st.owner == root && matches!(st.kind, StateKind::Signal | StateKind::Prop))
            .map(|st| {
                let field = module.strings.get(st.name).to_string();
                (
                    field.clone(),
                    format!("set_{}", sanitize(module.strings.get(st.name))),
                )
            })
            .collect(),
        templates: template_ids
            .iter()
            .map(|&tid| (tid as u32, format!("{prefix}TPL_T{tid}")))
            .collect(),
    };

    Ok((pieces, struct_name, digest, source_path.to_string(), links))
}

type StrPair = (lig_core::id::StrId, u64);

pub(crate) fn sanitize(name: &str) -> String {
    let cleaned: String = name
        .chars()
        .map(|c| {
            if c.is_ascii_alphanumeric() || c == '_' {
                c
            } else {
                '_'
            }
        })
        .collect();
    if cleaned.chars().next().is_some_and(|c| c.is_ascii_digit()) {
        format!("_{cleaned}")
    } else {
        cleaned
    }
}

fn tpl_ident(prefix: &str, tpl_id: usize) -> syn::Ident {
    syn::Ident::new(&format!("{prefix}TPL_T{tpl_id}"), Span::call_site())
}

fn hole_ident(prefix: &str, frag_id: usize) -> syn::Ident {
    syn::Ident::new(
        &format!("{prefix}HOLE_ANCHORS_F{frag_id}"),
        Span::call_site(),
    )
}

fn branch_ident(prefix: &str, frag_id: usize) -> syn::Ident {
    syn::Ident::new(
        &format!("{prefix}BRANCH_ANCHORS_F{frag_id}"),
        Span::call_site(),
    )
}

fn reaction_const_name(module: &ViewModule, r: &ReactionDecl, id: usize) -> String {
    match r.kind {
        ReactionKind::Memo { target } => format!(
            "R{}_MEMO_{}",
            id,
            sanitize(module.strings.get(target)).to_uppercase()
        ),
        ReactionKind::Effect { .. } => format!("R{id}_FX"),
        ReactionKind::Bind { dynamic } => format!("R{id}_BIND_D{dynamic}"),
    }
}

