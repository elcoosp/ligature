//! Codegen (D-8, §9): `quote!` → `syn::File` → `prettyplease`, byte-
//! reproducible, with grouped apply functions (C5), access-mode elision
//! (§9.3), and the readability budget enforced by a syn visitor (NFR-4).
//!
//! M0 codegen subset (spike S1): signals/memos, text/class/attr binds,
//! delegated event effects, `Show`-style branches, static style tables.
//! Component uses, dynamic style objects and slots are IR-expressible but
//! codegen-denied until M1 ([`CodegenError::Unsupported`]).

#![forbid(unsafe_code)]
#![deny(missing_docs)]

pub mod expr_gen;
pub mod readability;
pub mod template_gen;

