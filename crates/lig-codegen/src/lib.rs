fn emit_apply_fns(module: &ViewModule, frags: &[FragInfo]) -> Vec<proc_macro2::TokenStream> {
    let _ = (module, frags);
    Vec::new()
}

/// The per-For reconcile method (unkeyed Index diff, §7.5): mount new items,
/// remove tails, then refresh surviving items' binds with the new values.
#[allow(clippy::too_many_arguments)]
fn emit_list_method(
    module: &ViewModule,
    for_ir: &lig_ir::fragment::ForIr,
    item_ty: &Ty,
    body_info: &FragInfo,
    prefix: &str,
) -> Result<proc_macro2::TokenStream, CodegenError> {
    let src = gen_expr(module, for_ir.source)?;
    let item_ty_lit: syn::Type = syn::parse_str(&ty_name(item_ty)).expect("valid item type");
    let body_tpl = tpl_ident(prefix, body_info.template_id);
    let body_holes = hole_ident(prefix, body_info.id.get() as usize);
    let body_branches = branch_ident(prefix, body_info.id.get() as usize);
    let apply = syn::Ident::new(
        &format!("apply_item_f{}", for_ir.body.get()),
        Span::call_site(),
    );
    let method = syn::Ident::new(
        &format!("reconcile_f{}", for_ir.body.get()),
        Span::call_site(),
    );
    // Parent-state reads of the item binds, by value (borrow-split discipline:
    // the refresh loop holds `self.frag` mutably).
    let reads = collect_body_reads(module, for_ir.body);
    let read_declares: Vec<proc_macro2::TokenStream> = reads
        .iter()
        .map(|r| {
            let pname = syn::Ident::new(
                &format!("s_{}", sanitize(module.strings.get(*r))),
                Span::call_site(),
            );
            let fname = syn::Ident::new(&sanitize(module.strings.get(*r)), Span::call_site());
            quote! { let #pname = self.#fname.clone(); }
        })
        .collect();
    let read_args: Vec<proc_macro2::TokenStream> = reads
        .iter()
        .map(|r| {
            let pname = syn::Ident::new(
                &format!("s_{}", sanitize(module.strings.get(*r))),
                Span::call_site(),
            );
            quote! { #pname.clone() }
        })
        .collect();
    Ok(quote! {
        #[allow(clippy::needless_range_loop)]
        fn #method(&mut self, h: &mut dyn Host, slot: usize) {
            let items: ::alloc::vec::Vec<#item_ty_lit> = ::core::clone::Clone::clone(&(#src));
            let old = self.frag.list_len(slot);
            let common = old.min(items.len());
            for i in common..items.len() {
                self.frag.list_insert(h, slot, i, i as u64, #body_tpl, #body_holes, #body_branches);
            }
            for i in (common..old).rev() {
                self.frag.list_remove(h, slot, i);
            }
            #(#read_declares)*
            for (i, it) in items.iter().enumerate().take(common) {
                if let Some(f) = self.frag.list_item_mut(slot, i) {
                    #apply(f, h, it.clone(), i as i64, #(#read_args),*);
                }
            }
        }
    })
}

/// The `State` names read by a For body fragment's binds (sorted, deduped).
fn collect_body_reads(module: &ViewModule, body: FragmentId) -> Vec<StrId> {
    use lig_ir::expr::Expr as E;
    fn walk(e: &E, out: &mut Vec<StrId>) {
        match e {
            E::State(s) => out.push(*s),
            E::Field(inner, _) | E::Unary(_, inner) => walk(inner, out),
            E::Index(a, b) | E::Binary(_, a, b) | E::Ternary(a, b, _) => {
                walk(a, out);
                walk(b, out);
            }
            E::Array(items) => items.iter().for_each(|i| walk(i, out)),
            E::Tpl(parts) => {
                for p in parts {
                    if let lig_ir::expr::TplPart::Hole(h) = p {
                        walk(h, out);
                    }
                }
            }
            E::Call(_, args) => args.iter().for_each(|a| walk(a, out)),
            _ => {}
        }
    }
    let Some(frag) = module.fragments.get(body.get() as usize) else {
        return Vec::new();
    };
    let mut out = Vec::new();
    for d in &frag.dynamics {
        walk(module.exprs.get(d.expr), &mut out);
    }
    out.sort();
    out.dedup();
    out
}

/// The per-item bind replay: one method covering the body fragment's binds,
/// with `item`/`index` locals substituted and parent state reads via `self`.
fn emit_item_method(
    module: &ViewModule,
    for_ir: &lig_ir::fragment::ForIr,
    item_ty: &Ty,
) -> Result<proc_macro2::TokenStream, CodegenError> {
    let body_frag = &module.fragments[for_ir.body.get() as usize];
    let item_ty_lit: syn::Type = syn::parse_str(&ty_name(item_ty)).expect("valid item type");
    let reads = collect_body_reads(module, for_ir.body);
    let read_params: Vec<proc_macro2::TokenStream> = reads
        .iter()
        .map(|r| {
            let pname = syn::Ident::new(
                &format!("s_{}", sanitize(module.strings.get(*r))),
                Span::call_site(),
            );
            let ty: syn::Type = syn::parse_str(&ty_name(
                &module.state_by_name(*r).map_or(Ty::Int, |d| d.ty.clone()),
            ))
            .expect("valid state type");
            quote! { #pname: #ty }
        })
        .collect();
    let mut commits: Vec<proc_macro2::TokenStream> = Vec::new();
    for (di, d) in body_frag.dynamics.iter().enumerate() {
        match &d.kind {
            DynamicKind::Text => {
                let v = gen_item_expr(module, d.expr, for_ir, item_ty)?;
                // The item binding is the apply fn's `String` param (deref
                // coerces at `&str`); the index binding is `i64` and must
                // stringify; parent-state reads follow their declared type.
                let is_str = match module.exprs.get(d.expr) {
                    lig_ir::expr::Expr::Local(l) if *l == for_ir.item => true,
                    lig_ir::expr::Expr::Local(l) if for_ir.index.is_some_and(|ix| ix == *l) => {
                        false
                    }
                    other => matches!(
                        codegen_ty_of(module, other),
                        Ty::Str | Ty::List(_) | Ty::Bool
                    ),
                };
                if is_str {
                    commits.push(quote! { f.set_text(h, #di, &(#v)); });
                } else {
                    commits.push(quote! {
                        {
                            let mut buf = [0u8; 20];
                            f.set_text(h, #di, ::lig_runtime::format_i64(&mut buf, #v));
                        }
                    });
                }
            }
            DynamicKind::Class => {
                let v = gen_item_expr(module, d.expr, for_ir, item_ty)?;
                commits.push(quote! { f.set_class(h, #di, Some(&(#v))); });
            }
            DynamicKind::Attr { key } => {
                let key_lit = syn::LitStr::new(module.strings.get(*key), Span::call_site());
                let v = gen_item_expr(module, d.expr, for_ir, item_ty)?;
                let is_str = matches!(
                    codegen_ty_of(module, module.exprs.get(d.expr)),
                    Ty::Str | Ty::List(_) | Ty::Bool
                );
                if is_str {
                    commits.push(quote! {
                        f.set_attr(h, #di, #key_lit, Some(::lig_runtime::AttrVal::Str(&(#v))));
                    });
                } else {
                    commits.push(quote! {
                        f.set_attr(h, #di, #key_lit, Some(::lig_runtime::AttrVal::Num((#v) as f64)));
                    });
                }
            }
            DynamicKind::StyleProp { prop } => {
                let prop_id = prop.get();
                let v = gen_item_expr(module, d.expr, for_ir, item_ty)?;
                commits.push(quote! {
                    f.set_style_dyn(h, #di, &[(#prop_id, ::lig_runtime::PropVal::Raw(&(#v)))]);
                });
            }
            DynamicKind::Event { .. } => {
                return Err(CodegenError::Unsupported(
                    "event handlers inside list item bodies are not admitted in v1 \
                     (LIG-E118) — hoist to the list level or a keyed component",
                ));
            }
            DynamicKind::If(_)
            | DynamicKind::For(_)
            | DynamicKind::Component(_)
            | DynamicKind::Html
            | DynamicKind::Ref
            | DynamicKind::Slot { .. }
            | DynamicKind::Children
            | DynamicKind::PropPass { .. }
            | DynamicKind::Style => {
                return Err(CodegenError::Unsupported(
                    "control flow inside list item bodies is not admitted in v1",
                ));
            }
        }
    }
    let method = syn::Ident::new(
        &format!("apply_item_f{}", for_ir.body.get()),
        proc_macro2::Span::call_site(),
    );
    Ok(quote! {
        fn #method(f: &mut ::lig_runtime::Fragment, h: &mut dyn Host,
                   item: #item_ty_lit, index: i64, #(#read_params,)*) {
            #(#commits)*
        }
    })
}

/// `gen_expr` with `item`/`index` locals resolved (item bodies see the item
/// value and position; parent state reads stay `self.<field>`).
fn gen_item_expr(
    module: &ViewModule,
    id: ExprId,
    for_ir: &lig_ir::fragment::ForIr,
    _item_ty: &Ty,
) -> Result<proc_macro2::TokenStream, CodegenError> {
    let expr = module.exprs.get(id);
    match expr {
        lig_ir::expr::Expr::Local(l) => {
            if *l == for_ir.item {
                Ok(quote!(item))
            } else if for_ir.index.is_some_and(|ix| ix == *l) {
                Ok(quote!(index))
            } else {
                Err(CodegenError::Unsupported(
                    "locals other than the item/index bindings are not admitted in list item bodies (v1)",
                ))
            }
        }
        lig_ir::expr::Expr::State(name) => {
            // Parent-state reads arrive as `s_<field>` parameters (the item
            // replay runs while `self.frag` is mutably borrowed).
            let pname = syn::Ident::new(
                &format!("s_{}", sanitize(module.strings.get(*name))),
                Span::call_site(),
            );
            Ok(quote!(#pname))
        }
        other => {
            // Literals, field/index chains, calls: the standard generator
            // (its `self.`-prefixed State arm is overridden above).
            let _ = other;
            gen_expr(module, id)
        }
    }
}

/// Generate the Rust source for one source file's whole module (§9.5): all
/// components share one `generated` mod (cross-component references resolve
/// within it) plus façade re-exports. Byte-reproducible: components in
/// canonical (name-sorted) order.
///
/// # Errors
/// Any component failing codegen fails the module (fail-closed, BR-1).
pub fn generate_module(module: &ViewModule) -> Result<GeneratedModule, CodegenError> {
    let mut all_pieces: Vec<proc_macro2::TokenStream> = Vec::new();
    let mut exported: Vec<syn::Ident> = Vec::new();
    let mut exported_props: Vec<syn::Ident> = Vec::new();
    let mut links = GenLinks::default();
    for idx in 0..module.components.len() {
        let (pieces, struct_name, _digest, _src, component_links) =
            generate_component_pieces(module, ComponentId::new(idx as u32))?;
        all_pieces.extend(pieces);
        links.prefix = component_links.prefix;
        links.reactions.extend(component_links.reactions);
        links.setters.extend(component_links.setters);
        links.templates.extend(component_links.templates);
        exported_props.push(syn::Ident::new(
            &format!("{struct_name}Props"),
            proc_macro2::Span::call_site(),
        ));
        exported.push(struct_name);
    }
    let doc = syn::LitStr::new(
        "generated by ligature — do not edit",
        proc_macro2::Span::call_site(),
    );
    let all: proc_macro2::TokenStream = quote! {
        #[doc = #doc]
        #[allow(
            clippy::all,
            clippy::pedantic,
            missing_docs,
            non_upper_case_globals,
            unused_parens,
            unused_variables,
            dead_code
        )]
        pub mod generated {
            use ::lig_runtime::prelude::*;
            #(#all_pieces)*
        }
        #(pub use generated::#exported;)*
        #(pub use generated::#exported_props;)*
    };
    let file: syn::File = syn::parse2(all).expect("generated module tokens must parse");
    let violations = readability::check(&file);
    if !violations.is_empty() {
        return Err(CodegenError::Readability(violations));
    }
    Ok(GeneratedModule {
        text: prettyplease::unparse(&file),
        links,
    })
}

/// The module-level artifact: one generated file for the whole source file
/// plus its aggregated IR→generated link table (§9.5 + §9.4).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct GeneratedModule {
    /// The generated Rust source text.
    pub text: String,
    /// Aggregated link table across the module's components.
    pub links: GenLinks,
}
