//! Codegen (D-8, §9): `quote!` → `syn::File` → `prettyplease`, byte-
//! reproducible, with grouped apply functions (C5), access-mode elision
//! (§9.3), and the readability budget enforced by a syn visitor (NFR-4).
//!
//! M0 codegen subset (spike S1): signals/memos, text/class/attr binds,
//! delegated event effects, `Show`-style branches, static style tables.
//! Component uses, dynamic style objects and slots are IR-expressible but
//! codegen-denied until M1 ([`CodegenError::Unsupported`]).

#![forbid(unsafe_code)]
#![deny(missing_docs)]

pub mod expr_gen;
pub mod readability;
pub mod template_gen;

use expr_gen::{ValueKind, gen_expr, value_kind};
use lig_core::id::{ComponentId, ExprId, FragmentId, StrId};
use lig_ir::anchor::AnchorStep as IrStep;
use lig_ir::expr::Ty;
use lig_ir::fragment::{DynamicKind, FragmentIr, StateKind};
use lig_ir::module::{ReactionDecl, ReactionKind, ViewModule};
use lig_reactivity::{ComponentSchedule, ScheduleError, build_schedule};
use proc_macro2::Span;
use quote::quote;

/// A codegen failure (fail-closed — BR-1 applies to emission too).
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum CodegenError {
    /// The IR contains a construct outside the M0 codegen subset.
    Unsupported(&'static str),
    /// The reactivity schedule is invalid (cycle/capacity).
    Schedule(ScheduleError),
    /// The readability budget is violated — a codegen bug, not a lint (§9.3).
    Readability(Vec<readability::Violation>),
}

impl core::fmt::Display for CodegenError {
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        match self {
            CodegenError::Unsupported(what) => write!(f, "outside the M0 codegen subset: {what}"),
            CodegenError::Schedule(e) => write!(f, "schedule error: {e:?}"),
            CodegenError::Readability(vs) => write!(f, "readability budget violated: {vs:?}"),
        }
    }
}

impl std::error::Error for CodegenError {}

/// The emitted artifact.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct GeneratedUnit {
    /// The generated Rust source text (prettyplease; byte-reproducible, D-8).
    pub text: String,
    /// The component that produced it.
    pub component: ComponentId,
    /// Stable name markers linking IR nodes to generated symbols (§9.4
    /// source maps consume these; no text scanning in consumers).
    pub links: GenLinks,
}

/// IR → generated-symbol links for one component.
#[derive(Debug, Clone, PartialEq, Eq, Default)]
pub struct GenLinks {
    /// The static-name prefix of this component (`Counter_`).
    pub prefix: String,
    /// `(reaction id, generated const name)` in reaction order.
    pub reactions: Vec<(u32, String)>,
    /// `(state field, generated setter fn name)`.
    pub setters: Vec<(String, String)>,
    /// `(template id, generated static name)`.
    pub templates: Vec<(u32, String)>,
}

/// One fragment's emission data.
struct FragInfo {
    id: FragmentId,
    template_id: usize,
    /// Anchor path per dynamic (dynamic index = hole index).
    hole_paths: Vec<Vec<IrStep>>,
    /// Anchor path per branch slot (If/For dynamics in order).
    branch_paths: Vec<Vec<IrStep>>,
}

/// Per-reaction emission data.
struct RxInfo<'m> {
    id: usize,
    decl: &'m ReactionDecl,
    const_name: String,
}

/// Generate the Rust source for one component (§9.2 shape).
///
/// # Errors
/// [`CodegenError`] for constructs outside the M0 subset, invalid schedules,
/// or readability-budget violations.
/// Generate the Rust source for one component (§9.2 shape) as a standalone
/// single-component file.
///
/// # Errors
/// [`CodegenError`] for constructs outside the M1 subset, invalid schedules,
/// or readability-budget violations.
// One arm per dynamic kind keeps the §9.2 emission auditable end-to-end.
#[allow(clippy::too_many_lines)]
pub fn generate_component(
    module: &ViewModule,
    component: ComponentId,
) -> Result<GeneratedUnit, CodegenError> {
    let (pieces, struct_name, digest, source_path, links) =
        generate_component_pieces(module, component)?;
    let source_path: &str = &source_path;
    let digest_lit = format!("{digest:#x}");
    let header = format!(
        "generated by ligature — do not edit\nsource: {source_path} (component digest {digest_lit})"
    );
    let doc = syn::LitStr::new(&header, Span::call_site());
    let all: proc_macro2::TokenStream = quote! {
        #[doc = #doc]
        #[allow(
            clippy::all,
            clippy::pedantic,
            missing_docs,
            non_upper_case_globals,
            unused_parens,
            unused_variables,
            dead_code
        )]
        pub mod generated {
            use ::lig_runtime::prelude::*;
            #(#pieces)*
        }
        pub use generated::#struct_name;
    };
    let file: syn::File = syn::parse2(all).expect("generated tokens must parse");
    let violations = readability::check(&file);
    if !violations.is_empty() {
        return Err(CodegenError::Readability(violations));
    }
    let text = prettyplease::unparse(&file);
    Ok(GeneratedUnit {
        text,
        component,
        links,
    })
}

/// Build the item tokens for one component (the shared core of
/// [`generate_component`] and [`generate_module`]). Returns the pieces, the
/// component struct ident, the surface digest, and the source path.
#[allow(clippy::type_complexity)]
fn generate_component_pieces(
    module: &ViewModule,
    component: ComponentId,
) -> Result<
    (
        Vec<proc_macro2::TokenStream>,
        syn::Ident,
        u64,
        String,
        GenLinks,
    ),
    CodegenError,
> {
    let Some(decl) = module.components.get(component.get() as usize) else {
        return Err(CodegenError::Unsupported("missing component declaration"));
    };
    let Some(root) = module.component_root(component) else {
        return Err(CodegenError::Unsupported("missing component root"));
    };
    let schedule = build_schedule(module, root).map_err(CodegenError::Schedule)?;

    let struct_name = syn::Ident::new(&sanitize(module.strings.get(decl.name)), Span::call_site());
    let prefix = format!("{struct_name}_");

    // --- fragments -----------------------------------------------------------
    let frags = collect_frag_infos(module, root);
    let root_info = &frags[0];

    // --- templates (deduped by template id, BTree order = deterministic) ----
    let mut template_ids: Vec<usize> = frags.iter().map(|f| f.template_id).collect();
    template_ids.sort_unstable();
    template_ids.dedup();
    let template_statics: Vec<_> = template_ids
        .iter()
        .map(|&tid| template_gen::gen_template_static(module, tid, &prefix))
        .collect();

    // --- anchors per fragment ------------------------------------------------
    let anchor_statics: Vec<_> = frags
        .iter()
        .map(|f| {
            template_gen::gen_anchor_statics(
                f.id.get() as usize,
                &f.hole_paths,
                &f.branch_paths,
                &prefix,
            )
        })
        .collect();

    // --- reactions of this component (module order) ---------------------------
    let for_bodies: Vec<FragmentId> = module
        .fragments
        .iter()
        .flat_map(|f| f.dynamics.iter())
        .filter_map(|d| match &d.kind {
            DynamicKind::For(f) => Some(f.body),
            _ => None,
        })
        .collect();
    let rxs: Vec<RxInfo<'_>> = module
        .reactions
        .iter()
        .enumerate()
        .filter(|(_, r)| fragment_in_tree(&frags, r.owner) && !for_bodies.contains(&r.owner))
        .map(|(id, r)| RxInfo {
            id,
            decl: r,
            const_name: reaction_const_name(module, r, id),
        })
        .collect();
    let n_reactions = rxs.len();
    let max_rx_id = rxs.iter().map(|r| r.id).max().map_or(0, |m| m + 1);
    let _ = max_rx_id;

    // --- SCHEDULE + WRITES -----------------------------------------------------
    let schedule_items = {
        let order: Vec<u8> = schedule.order.iter().map(|r| r.get() as u8).collect();
        let writes: Vec<u64> = (0..max_rx_id)
            .map(|i| schedule.reaction_writes.get(i).copied().unwrap_or(0))
            .collect();
        let sched_name = syn::Ident::new(&format!("{prefix}SCHEDULE"), Span::call_site());
        quote! {
            static #sched_name: ::lig_runtime::Schedule = ::lig_runtime::Schedule {
                order: &[ #(#order),* ],
                writes: &[ #(#writes),* ],
            };
        }
    };

    let sched_ident = syn::Ident::new(&format!("{prefix}SCHEDULE"), Span::call_site());

    // --- READS masks per state field -------------------------------------------
    let reads_consts: Vec<_> = {
        let mut out = Vec::new();
        let mut fields: Vec<StrPair> = schedule
            .field_readers
            .iter()
            .map(|(k, v)| (*k, *v))
            .collect();
        fields.sort_by_key(|(k, _)| k.get());
        for (field, mask) in fields {
            let name = syn::Ident::new(
                &format!(
                    "{prefix}READS_{}",
                    sanitize(module.strings.get(field)).to_uppercase()
                ),
                Span::call_site(),
            );
            out.push(quote! { const #name: u64 = #mask; });
        }
        out
    };

    // --- state struct fields + initializers --------------------------------------
    let mut struct_fields: Vec<proc_macro2::TokenStream> = Vec::new();
    let mut init_fields: Vec<proc_macro2::TokenStream> = Vec::new();
    for st in module.states.iter().filter(|s| s.owner == root) {
        let fname = syn::Ident::new(&sanitize(module.strings.get(st.name)), Span::call_site());
        let ty: syn::Type = syn::parse_str(&ty_name(&st.ty)).expect("valid type name");
        struct_fields.push(quote! { pub #fname: #ty });
        let init = match (st.kind, st.init) {
            (StateKind::Prop, _) => {
                // Props arrive through the `<Name>Props` argument (§7.6).
                quote! { props.#fname }
            }
            (StateKind::Signal | StateKind::Memo | StateKind::Cond | StateKind::Local, Some(e))
                if init_is_literal(module, e) =>
            {
                let v = gen_expr(module, e)?;
                if matches!(st.ty, Ty::Str) {
                    quote! { ::alloc::string::String::from(#v) }
                } else {
                    v
                }
            }
            (StateKind::Signal, Some(_)) => {
                return Err(CodegenError::Unsupported(
                    "non-literal signal initializers (M1 model codegen)",
                ));
            }
            _ => default_value(&st.ty),
        };
        init_fields.push(quote! { #fname: #init });
    }
    struct_fields.push(quote! { pub ev: ::lig_runtime::EvData });
    init_fields.push(quote! { ev: ::lig_runtime::EvData::new() });
    struct_fields.push(quote! { pub frag: ::lig_runtime::Fragment });

    // --- child component instances (fields + build) --------------------------------
    let component_uses = collect_component_uses(module, root);
    for (field, comp_idx, _dyn) in &component_uses {
        let Some(decl) = module.components.get(*comp_idx) else {
            return Err(CodegenError::Unsupported("missing component declaration"));
        };
        let child_name = sanitize(module.strings.get(decl.name));
        let fname = syn::Ident::new(field, Span::call_site());
        let child_ty = syn::Ident::new(&child_name, Span::call_site());
        let props_ty = syn::Ident::new(&format!("{child_name}Props"), Span::call_site());
        struct_fields.push(quote! { pub #fname: #child_ty });
        init_fields.push(quote! {
            #fname: #child_ty::build(h, #props_ty::default())
        });
    }

    // --- StyleProp prev slots (per-dynamic prev diff, §8.2/C5) ----------------------
    let mut prev_fields: Vec<proc_macro2::TokenStream> = Vec::new();
    let mut prev_inits: Vec<proc_macro2::TokenStream> = Vec::new();
    for p in collect_styleprop_dynamics(module, root) {
        let fname = syn::Ident::new(&format!("p_{p}"), Span::call_site());
        prev_fields.push(quote! { #fname: ::alloc::string::String });
        prev_inits.push(quote! { #fname: ::alloc::string::String::new() });
    }
    struct_fields.extend(prev_fields);
    init_fields.extend(prev_inits);

    // --- apply functions (grouped by (fragment, anchor) — C5) ---------------------
    let apply_fns = emit_apply_fns(module, &frags);
    let group_state_fields: Vec<proc_macro2::TokenStream> = Vec::new();

    // --- run arms -------------------------------------------------------------
    let mut run_arms: Vec<proc_macro2::TokenStream> = Vec::new();
    let mut list_methods: Vec<proc_macro2::TokenStream> = Vec::new();
    let mut item_methods: Vec<proc_macro2::TokenStream> = Vec::new();
    let mut ref_captures: Vec<(String, usize)> = Vec::new();
    for rx in &rxs {
        let cname = syn::Ident::new(&format!("{prefix}{}", rx.const_name), Span::call_site());
        match rx.decl.kind {
            ReactionKind::Memo { target } => {
                let tname =
                    syn::Ident::new(&sanitize(module.strings.get(target)), Span::call_site());
                let body = gen_expr(module, rx.decl.body)?;
                let reads_mask = field_mask(&schedule, target);
                run_arms.push(quote! {
                    #cname => {
                        let next = #body;
                        if next != self.#tname {
                            self.#tname = next;
                            self.frag.mark_mask(#reads_mask);
                        }
                    }
                });
            }
            ReactionKind::Effect { .. } => {
                // event handler body: setter calls as statements
                let body = gen_expr(module, rx.decl.body)?;
                run_arms.push(quote! {
                    #cname => {
                        #body;
                    }
                });
            }
            ReactionKind::Bind { dynamic } => {
                let frag = module.fragments.get(rx.decl.owner.get() as usize);
                let Some(frag) = frag else { continue };
                let Some(d) = frag.dynamics.get(dynamic as usize) else {
                    continue;
                };
                let hole_idx = dynamic as usize;
                match &d.kind {
                    DynamicKind::Text => {
                        let is_str =
                            value_kind(module, module.exprs.get(rx.decl.body)) == ValueKind::Str;
                        let body = gen_expr(module, rx.decl.body)?;
                        let owner_in_branch = branch_slot_of(module, &frags, rx.decl.owner);
                        if let Some(slot) = owner_in_branch {
                            if is_str {
                                run_arms.push(quote! {
                                    #cname => {
                                        if let Some(b) = self.frag.branch_mut(#slot) {
                                            b.set_text(h, #hole_idx, &#body);
                                        }
                                    }
                                });
                            } else {
                                run_arms.push(quote! {
                                    #cname => {
                                        if let Some(b) = self.frag.branch_mut(#slot) {
                                            let mut buf = [0u8; 20];
                                            b.set_text(h, #hole_idx, ::lig_runtime::format_i64(&mut buf, #body));
                                        }
                                    }
                                });
                            }
                        } else if is_str {
                            run_arms.push(quote! {
                                #cname => {
                                    self.frag.set_text(h, #hole_idx, &#body);
                                }
                            });
                        } else {
                            run_arms.push(quote! {
                                #cname => {
                                    let mut buf = [0u8; 20];
                                    self.frag.set_text(h, #hole_idx, ::lig_runtime::format_i64(&mut buf, #body));
                                }
                            });
                        }
                    }
                    DynamicKind::Class => {
                        let body = gen_expr(module, rx.decl.body)?;
                        run_arms.push(quote! {
                            #cname => {
                                self.frag.set_class(h, #hole_idx, Some(&(#body)));
                            }
                        });
                    }
                    DynamicKind::Attr { key } => {
                        let key_lit = syn::LitStr::new(module.strings.get(*key), Span::call_site());
                        let body = gen_expr(module, rx.decl.body)?;
                        let is_str =
                            value_kind(module, module.exprs.get(rx.decl.body)) == ValueKind::Str;
                        if is_str {
                            run_arms.push(quote! {
                                #cname => {
                                    self.frag.set_attr(h, #hole_idx, #key_lit, Some(::lig_runtime::AttrVal::Str(&(#body))));
                                }
                            });
                        } else {
                            run_arms.push(quote! {
                                #cname => self.frag.set_attr(h, #hole_idx, #key_lit, Some(::lig_runtime::AttrVal::Num((#body) as f64)));
                            });
                        }
                    }
                    DynamicKind::If(if_ir) => {
                        let cond = gen_expr(module, if_ir.cond)?;
                        let slot = branch_slot_of_dynamic(frag, dynamic);
                        let Some(slot) = slot else { continue };
                        let branch_info = frags.iter().find(|f| f.id == if_ir.then);
                        let Some(branch_info) = branch_info else {
                            continue;
                        };
                        let b_tpl = tpl_ident(&prefix, branch_info.template_id);
                        let b_holes = hole_ident(&prefix, branch_info.id.get() as usize);
                        let b_branches = branch_ident(&prefix, branch_info.id.get() as usize);
                        run_arms.push(quote! {
                            #cname => {
                                let on = #cond;
                                if self.frag.branch_is(#slot) != on {
                                    if on {
                                        self.frag.mount_branch(h, #slot, #b_tpl, #b_holes, #b_branches);
                                    } else {
                                        self.frag.unmount_branch(h, #slot);
                                    }
                                }
                            }
                        });
                    }
                    DynamicKind::For(for_ir) => {
                        // Unkeyed list reconcile (Index semantics, §7.5): the
                        // keyed LIS diff ships as the runtime primitive
                        // (`keyed_diff`, bench-gated) and drives patch-mode
                        // updates; v1 fixtures use Solid `<For>`/`.map`
                        // (unkeyed). Emission goes through a per-For method.
                        let slot = branch_slot_of_dynamic(frag, dynamic);
                        let Some(slot) = slot else { continue };
                        let body_info = frags.iter().find(|f| f.id == for_ir.body);
                        let Some(body_info) = body_info else { continue };
                        let src_ty = codegen_ty_of(module, module.exprs.get(for_ir.source));
                        let lig_ir::expr::Ty::List(item_ty) = &src_ty else {
                            return Err(CodegenError::Unsupported(
                                "For source must lower to a list type",
                            ));
                        };
                        let item_ty = (**item_ty).clone();
                        let method = syn::Ident::new(
                            &format!("reconcile_f{}", for_ir.body.get()),
                            Span::call_site(),
                        );
                        run_arms.push(quote! {
                            #cname => {
                                self.#method(h, #slot);
                            }
                        });
                        list_methods.push(emit_list_method(
                            module, for_ir, &item_ty, body_info, &prefix,
                        )?);
                        item_methods.push(emit_item_method(module, for_ir, &item_ty)?);
                    }
                    DynamicKind::Component(c) => {
                        // Prop-pass (§7.6): direct writes on the child's
                        // state + a child flush; the child's own reactions
                        // run from its schedule.
                        let field = syn::Ident::new(
                            &field_name_for(module, c.component),
                            Span::call_site(),
                        );
                        let mut sets = Vec::new();
                        for pb in &c.props {
                            let setter = syn::Ident::new(
                                &format!("set_{}", sanitize(module.strings.get(pb.prop))),
                                Span::call_site(),
                            );
                            let raw = gen_expr(module, pb.value)?;
                            let v = match module.exprs.get(pb.value) {
                                lig_ir::expr::Expr::Lit(lig_ir::expr::Lit::Str(_)) => {
                                    quote!(::alloc::string::String::from(#raw))
                                }
                                _ => raw,
                            };
                            sets.push(quote! { self.#field.#setter(#v); });
                        }
                        if sets.is_empty() {
                            // No dynamic props: nothing to do per update.
                        } else {
                            run_arms.push(quote! {
                                #cname => {
                                    #(#sets)*
                                    ::lig_runtime::flush(&mut self.#field, h);
                                }
                            });
                        }
                    }
                    DynamicKind::StyleProp { prop } => {
                        let body = gen_expr(module, rx.decl.body)?;
                        let prop_id = prop.get();
                        let pname = syn::Ident::new(&format!("p_{dynamic}"), Span::call_site());
                        let hole_idx = dynamic as usize;
                        run_arms.push(quote! {
                            #cname => {
                                let v: ::alloc::string::String = ::core::clone::Clone::clone(&(#body));
                                if v != self.#pname {
                                    self.#pname = v.clone();
                                    self.frag.set_style_dyn(
                                        h,
                                        #hole_idx,
                                        &[(#prop_id, ::lig_runtime::PropVal::Raw(&v))],
                                    );
                                }
                            }
                        });
                    }
                    DynamicKind::Html => {
                        let body = gen_expr(module, rx.decl.body)?;
                        let hole_idx = dynamic as usize;
                        run_arms.push(quote! {
                            #cname => {
                                self.frag.set_html(h, #hole_idx, &(#body));
                            }
                        });
                    }
                    DynamicKind::Ref => {
                        // Build-time: the ref local captures the hole NodeId.
                        if let lig_ir::expr::Expr::Local(name) = module.exprs.get(rx.decl.body) {
                            ref_captures
                                .push((sanitize(module.strings.get(*name)), dynamic as usize));
                        } else {
                            return Err(CodegenError::Unsupported(
                                "ref must be a local binding in v1",
                            ));
                        }
                    }
                    DynamicKind::Event { event, delegate } => {
                        // attach-only metadata; the run arm is the Effect's
                        let _ = (event, delegate);
                    }
                    DynamicKind::Slot { .. } => {
                        // The parent mounts slot fills; the child reserves
                        // the hole (§7.4).
                    }
                    DynamicKind::Children | DynamicKind::PropPass { .. } | DynamicKind::Style => {
                        return Err(CodegenError::Unsupported(
                            "children/prop-pass/whole-style dynamics (M2)",
                        ));
                    }
                }
            }
        }
    }

    // --- attach list (event dynamics of ALL fragments in tree order) ----------
    let mut attaches: Vec<proc_macro2::TokenStream> = Vec::new();
    let mut dispatch_bits: u64 = 0;
    for f in &frags {
        let frag = &module.fragments[f.id.get() as usize];
        for (di, d) in frag.dynamics.iter().enumerate() {
            if let DynamicKind::Event { event, delegate } = &d.kind {
                let Some(rx_id) = d.reaction else { continue };
                dispatch_bits |= 1u64 << rx_id.get();
                let ev = syn::Ident::new(&format!("{event:?}"), Span::call_site());
                let h = rx_id.get();
                attaches.push(quote! {
                    s.frag.attach(h, #di, ::lig_runtime::EventKind::#ev, ::lig_runtime::HandlerId(#h), #delegate);
                });
            }
        }
    }

    // --- setters (signals + props; §7.6 props are plain fields with setters) ----
    let mut setters: Vec<proc_macro2::TokenStream> = Vec::new();
    for st in module
        .states
        .iter()
        .filter(|s| s.owner == root && (s.kind == StateKind::Signal || s.kind == StateKind::Prop))
    {
        let fname = syn::Ident::new(&sanitize(module.strings.get(st.name)), Span::call_site());
        let setter = syn::Ident::new(
            &format!("set_{}", sanitize(module.strings.get(st.name))),
            Span::call_site(),
        );
        let ty: syn::Type = syn::parse_str(&ty_name(&st.ty)).expect("valid type name");
        let mask = field_mask(&schedule, st.name);
        setters.push(quote! {
            /// Generated setter — the only write path for this signal (§9.2).
            pub fn #setter(&mut self, v: #ty) {
                self.#fname = v;
                self.frag.mark_mask(#mask);
            }
        });
    }

    // --- event glue fns ----------------------------------------------------------
    let mut event_fns: Vec<proc_macro2::TokenStream> = Vec::new();
    for rx in &rxs {
        if matches!(rx.decl.kind, ReactionKind::Effect { .. }) {
            let fname = syn::Ident::new(&format!("fire_{}", rx.id), Span::call_site());
            let rid = rx.id;
            event_fns.push(quote! {
                /// Dispatch glue: capture the event payload, mark the handler
                /// reaction, and flush (§10.1).
                pub fn #fname(&mut self, h: &mut dyn Host, ev: &::lig_runtime::EvData) {
                    self.ev = ev.clone();
                    self.frag.dirty.set(#rid as usize);
                    ::lig_runtime::flush(self, h);
                }
            });
        }
    }

    // --- build ----------------------------------------------------------------------
    let init_mask: u64 = if n_reactions < 64 {
        ((1u64 << n_reactions) - 1) & !dispatch_bits
    } else {
        // Spill path: mark everything (the 64-reaction fast path covers all
        // v1 fixtures; spill + per-bit dispatch refinement is an M3 item).
        u64::MAX
    };
    let init_mask_lit = format!("{init_mask:#x}").replace("0x", "0x");
    let init_mask_lit = syn::LitInt::new(&init_mask_lit, Span::call_site());
    let root_tpl = tpl_ident(&prefix, root_info.template_id);
    let root_holes = hole_ident(&prefix, root_info.id.get() as usize);
    let root_branches = branch_ident(&prefix, root_info.id.get() as usize);

    // Slot fills: mount each used child's slot content (§7.4) after the
    // child exists. Slot dynamic index = its index among the child's dynamics.
    let mut slot_fills: Vec<proc_macro2::TokenStream> = Vec::new();
    for (field, comp_idx, dyn_idx) in &component_uses {
        let Some(child_root) =
            module.component_root(lig_core::id::ComponentId::new(*comp_idx as u32))
        else {
            continue;
        };
        let child_frag = &module.fragments[child_root.get() as usize];
        for (di, d) in child_frag.dynamics.iter().enumerate() {
            if let DynamicKind::Slot { name: slot_name } = &d.kind {
                // Find the matching fill: the parent's ComponentIr slot with
                // the same name, mounted from THIS use site's fills.
                let Some(fill_id) = module
                    .fragments
                    .iter()
                    .flat_map(|f| f.dynamics.iter())
                    .find_map(|d| match &d.kind {
                        DynamicKind::Component(c) if c.component.get() as usize == *comp_idx => c
                            .slots
                            .iter()
                            .find(|s| s.name == *slot_name)
                            .and_then(|s| s.fallback),
                        _ => None,
                    })
                else {
                    continue;
                };
                let Some(fill_info) = frags.iter().find(|f| f.id == fill_id) else {
                    continue;
                };
                let f_tpl = tpl_ident(&prefix, fill_info.template_id);
                let f_holes = hole_ident(&prefix, fill_info.id.get() as usize);
                let f_branches = branch_ident(&prefix, fill_info.id.get() as usize);
                let fname = syn::Ident::new(field, Span::call_site());
                slot_fills.push(quote! {
                    s.#fname.frag.mount_slot(h, #di, #f_tpl, #f_holes, #f_branches);
                });
            }
        }
        let _ = dyn_idx;
    }

    // Ref captures: `ref={el}` stores the hole NodeId on the named field.
    let ref_inits: Vec<proc_macro2::TokenStream> = ref_captures
        .iter()
        .map(|(name, hole)| {
            let fname = syn::Ident::new(&format!("ref_{name}"), Span::call_site());
            quote! { s.#fname = s.frag.hole(#hole); }
        })
        .collect();
    for (name, _hole) in &ref_captures {
        let fname = syn::Ident::new(&format!("ref_{name}"), Span::call_site());
        struct_fields.push(quote! { pub #fname: ::lig_runtime::NodeId });
        init_fields.push(quote! { #fname: ::lig_runtime::NodeId(u32::MAX) });
    }

    // Props struct: fields mirror the component's Prop declarations (§7.6).
    let decl = module.components.get(component.get() as usize);
    let props_fields: Vec<proc_macro2::TokenStream> = decl
        .map(|d| {
            d.props
                .iter()
                .map(|p| {
                    let f =
                        syn::Ident::new(&sanitize(module.strings.get(p.name)), Span::call_site());
                    let ty: syn::Type = syn::parse_str(&ty_name(&p.ty)).expect("valid type name");
                    quote! { pub #f: #ty }
                })
                .collect()
        })
        .unwrap_or_default();
    let props_ty = syn::Ident::new(&format!("{struct_name}Props"), Span::call_site());

    let digest = module.fingerprint_fragment(root);
    let source_path = module
        .source_files
        .first()
        .map_or("unknown", |f| f.path.as_str());

    // --- assemble ------------------------------------------------------------
    let group_inits: Vec<proc_macro2::TokenStream> = Vec::new();
    let mut pieces: Vec<proc_macro2::TokenStream> = Vec::new();

    let n_rx = syn::Ident::new(&format!("{prefix}N_REACTIONS"), Span::call_site());
    pieces.push(quote! {
        pub struct #struct_name {
            #(#struct_fields,)*
            #(#group_state_fields,)*
        }
        #[derive(Default)]
        pub struct #props_ty {
            #(#props_fields,)*
        }
        const #n_rx: usize = #n_reactions;
    });
    pieces.extend(template_statics);
    pieces.extend(anchor_statics);
    pieces.push(schedule_items);
    for c in reads_consts {
        pieces.push(quote! { #c });
    }
    for rx in &rxs {
        let cname = syn::Ident::new(&format!("{prefix}{}", rx.const_name), Span::call_site());
        let rid = rx.id as u8;
        pieces.push(quote! { const #cname: u8 = #rid; });
    }
    pieces.push(quote! {
        impl #struct_name {
            #(#setters)*

            #(#event_fns)*

            #(#list_methods)*

            /// Run-once build (C4): executes top-to-bottom; reactivity lives
            /// exclusively in reactions.
            pub fn build(h: &mut dyn Host, props: #props_ty) -> Self {
                let mut s = Self {
                    #(#init_fields,)*
                    #(#group_inits,)*
                    frag: ::lig_runtime::Fragment::new(h, #root_tpl, #root_holes, #root_branches),
                };
                #(#slot_fills)*
                #(#ref_inits)*
                #(#attaches)*
                // Initial pass: memos + binds only — dispatch-driven handler
                // reactions run on events, never at build (§9.2 run-once).
                s.frag.mark_mask(#init_mask_lit);
                ::lig_runtime::flush(&mut s, h);
                s
            }
        }
    });
    pieces.push(quote! {
        impl ::lig_runtime::Reactions for #struct_name {
            fn schedule(&self) -> &'static ::lig_runtime::Schedule {
                &#sched_ident
            }

            fn dirty(&mut self) -> &mut ::lig_runtime::DirtySet {
                &mut self.frag.dirty
            }

            fn run(&mut self, h: &mut dyn Host, r: u8) {
                match r {
                    #(#run_arms)*
                    _ => {}
                }
            }
        }
    });
    pieces.extend(apply_fns);
    pieces.extend(item_methods);
    pieces.push(template_gen::gen_style_table(module, &prefix));

    // IR → generated-symbol links (source maps, §9.4).
    let links = GenLinks {
        prefix: prefix.clone(),
        reactions: rxs
            .iter()
            .map(|rx| (rx.id as u32, format!("{prefix}{}", rx.const_name)))
            .collect(),
        setters: module
            .states
            .iter()
            .filter(|st| st.owner == root && matches!(st.kind, StateKind::Signal | StateKind::Prop))
            .map(|st| {
                let field = module.strings.get(st.name).to_string();
                (
                    field.clone(),
                    format!("set_{}", sanitize(module.strings.get(st.name))),
                )
            })
            .collect(),
        templates: template_ids
            .iter()
            .map(|&tid| (tid as u32, format!("{prefix}TPL_T{tid}")))
            .collect(),
    };

    Ok((pieces, struct_name, digest, source_path.to_string(), links))
}

type StrPair = (lig_core::id::StrId, u64);

fn sanitize(name: &str) -> String {
    let cleaned: String = name
        .chars()
        .map(|c| {
            if c.is_ascii_alphanumeric() || c == '_' {
                c
            } else {
                '_'
            }
        })
        .collect();
    if cleaned.chars().next().is_some_and(|c| c.is_ascii_digit()) {
        format!("_{cleaned}")
    } else {
        cleaned
    }
}

fn tpl_ident(prefix: &str, tpl_id: usize) -> syn::Ident {
    syn::Ident::new(&format!("{prefix}TPL_T{tpl_id}"), Span::call_site())
}

fn hole_ident(prefix: &str, frag_id: usize) -> syn::Ident {
    syn::Ident::new(
        &format!("{prefix}HOLE_ANCHORS_F{frag_id}"),
        Span::call_site(),
    )
}

fn branch_ident(prefix: &str, frag_id: usize) -> syn::Ident {
    syn::Ident::new(
        &format!("{prefix}BRANCH_ANCHORS_F{frag_id}"),
        Span::call_site(),
    )
}

fn reaction_const_name(module: &ViewModule, r: &ReactionDecl, id: usize) -> String {
    match r.kind {
        ReactionKind::Memo { target } => format!(
            "R{}_MEMO_{}",
            id,
            sanitize(module.strings.get(target)).to_uppercase()
        ),
        ReactionKind::Effect { .. } => format!("R{id}_FX"),
        ReactionKind::Bind { dynamic } => format!("R{id}_BIND_D{dynamic}"),
    }
}

fn field_mask(schedule: &ComponentSchedule, field: lig_core::id::StrId) -> u64 {
    schedule.field_readers.get(&field).copied().unwrap_or(0)
}

fn ty_name(ty: &Ty) -> String {
    match ty {
        Ty::Str => "::alloc::string::String".to_string(),
        Ty::Bool => "bool".to_string(),
        Ty::Float => "f64".to_string(),
        Ty::List(inner) => format!("::alloc::vec::Vec<{}>", ty_name(inner)),
        Ty::Option(inner) => format!("::core::option::Option<{}>", ty_name(inner)),
        Ty::Int | Ty::Struct(_) | Ty::Never => "i64".to_string(),
    }
}

/// Backend-local small-lattice inference (mirrors the frontend's `ty_of`;
/// the typed forest plus state decls are the inputs).
fn codegen_ty_of(module: &ViewModule, e: &lig_ir::expr::Expr) -> Ty {
    use lig_ir::expr::{BinOp, Expr as E, Lit};
    match e {
        E::Lit(Lit::Float(_)) => Ty::Float,
        E::Lit(Lit::Bool(_))
        | E::Binary(
            BinOp::Eq
            | BinOp::Neq
            | BinOp::Lt
            | BinOp::Lte
            | BinOp::Gt
            | BinOp::Gte
            | BinOp::And
            | BinOp::Or,
            ..,
        ) => Ty::Bool,
        E::Lit(Lit::Str(_)) | E::Event(_) | E::Tpl(_) | E::Native(_) => Ty::Str,
        E::State(s) => module.state_by_name(*s).map_or(Ty::Int, |d| d.ty.clone()),
        E::Field(_, f) if module.strings.get(*f) == "length" => Ty::Int,
        E::Array(items) => Ty::List(Box::new(
            items.first().map_or(Ty::Int, |i| codegen_ty_of(module, i)),
        )),
        E::Ternary(_, a, _) => codegen_ty_of(module, a),
        // Int/Null literals and everything unlisted fall to the numeric
        // default (§5.5: unknown ⇒ Int).
        _ => Ty::Int,
    }
}

fn default_value(ty: &Ty) -> proc_macro2::TokenStream {
    match ty {
        Ty::Str => quote!(::alloc::string::String::new()),
        Ty::Bool => quote!(false),
        Ty::Float => quote!(0.0),
        Ty::List(_) => quote!(::alloc::vec::Vec::new()),
        _ => quote!(0),
    }
}

fn init_is_literal(module: &ViewModule, e: ExprId) -> bool {
    match module.exprs.get(e) {
        lig_ir::expr::Expr::Lit(_) => true,
        // List initializers: array of literals lowers to `vec![...]`.
        lig_ir::expr::Expr::Array(items) => items
            .iter()
            .all(|i| matches!(i, lig_ir::expr::Expr::Lit(_))),
        _ => false,
    }
}

/// Component-use sites in this component tree: `(field name, component id,
/// dynamic index)`, in template order.
fn collect_component_uses(module: &ViewModule, root: FragmentId) -> Vec<(String, usize, u32)> {
    let mut out = Vec::new();
    let mut stack = vec![root];
    while let Some(f) = stack.pop() {
        let Some(frag) = module.fragments.get(f.get() as usize) else {
            continue;
        };
        for (di, d) in frag.dynamics.iter().enumerate() {
            if let DynamicKind::Component(c) = &d.kind {
                let comp_name = module
                    .components
                    .get(c.component.get() as usize)
                    .map_or_else(
                        || "Child".to_string(),
                        |decl| module.strings.get(decl.name).to_string(),
                    );
                out.push((
                    sanitize(&comp_name).to_ascii_lowercase(),
                    c.component.get() as usize,
                    di as u32,
                ));
            }
        }
        for &c in &frag.children {
            stack.push(c);
        }
    }
    out.sort_by_key(|(_, _, di)| *di);
    out
}

/// The struct field name for a used child component (single use per parent
/// in v1; multi-use appends the dynamic index).
fn field_name_for(module: &ViewModule, component: ComponentId) -> String {
    let name = module.components.get(component.get() as usize).map_or_else(
        || "Child".to_string(),
        |decl| module.strings.get(decl.name).to_string(),
    );
    sanitize(&name).to_ascii_lowercase()
}

/// Every StyleProp dynamic index in this component tree (prev-slot fields).
fn collect_styleprop_dynamics(module: &ViewModule, root: FragmentId) -> Vec<u32> {
    let mut out = Vec::new();
    let mut stack = vec![root];
    while let Some(f) = stack.pop() {
        let Some(frag) = module.fragments.get(f.get() as usize) else {
            continue;
        };
        for (di, d) in frag.dynamics.iter().enumerate() {
            if matches!(d.kind, DynamicKind::StyleProp { .. }) {
                out.push(di as u32);
            }
        }
        for &c in &frag.children {
            stack.push(c);
        }
    }
    out
}

fn collect_frag_infos(module: &ViewModule, root: FragmentId) -> Vec<FragInfo> {
    let mut out = Vec::new();
    let mut stack = vec![root];
    while let Some(f) = stack.pop() {
        let Some(frag) = module.fragments.get(f.get() as usize) else {
            continue;
        };
        let mut hole_paths = Vec::new();
        let mut branch_paths = Vec::new();
        for d in &frag.dynamics {
            hole_paths.push(d.anchor.steps().to_vec());
            if let DynamicKind::If(_) | DynamicKind::For(_) = &d.kind {
                branch_paths.push(d.anchor.steps().to_vec());
            }
        }
        out.push(FragInfo {
            id: f,
            template_id: frag.template.get() as usize,
            hole_paths,
            branch_paths,
        });
        for &c in &frag.children {
            stack.push(c);
        }
    }
    out
}

fn fragment_in_tree(frags: &[FragInfo], f: FragmentId) -> bool {
    frags.iter().any(|fi| fi.id == f)
}

/// Branch slot of a fragment: its position among its PARENT's children.
/// parse-solid pushes branch fragments in If/For template order, so the
/// children position IS the branch slot for the spike shape.
fn branch_slot_of(module: &ViewModule, frags: &[FragInfo], f: FragmentId) -> Option<usize> {
    for info in frags {
        let parent = module.fragments.get(info.id.get() as usize)?;
        if let Some(slot) = parent.children.iter().position(|&c| c == f) {
            return Some(slot);
        }
    }
    None
}

fn branch_slot_of_dynamic(frag: &FragmentIr, dynamic: u32) -> Option<usize> {
    let mut slot = 0usize;
    for (di, d) in frag.dynamics.iter().enumerate() {
        if let DynamicKind::If(_) | DynamicKind::For(_) = &d.kind {
            if di as u32 == dynamic {
                return Some(slot);
            }
            slot += 1;
        }
    }
    None
}

